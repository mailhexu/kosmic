#!/usr/bin/env python3
"""Deterministic vault-level Shared Domain Skill Library.

Authoritative Markdown stays under ``memnotes/Skills``. Generated indexes are
reproducible, and resolution is a hash-pinned two-step operation.
"""

from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import tempfile
import unicodedata
from typing import Any, Iterable, Sequence

SCHEMA_VERSION = "kosmic.shared-library/v1"
GENERATOR_VERSION = 1
ID_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*(?:/(?:usage|development)/[a-z0-9]+(?:-[a-z0-9]+)*)?$")
SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
ROLES = {"usage", "development", "auto"}
STATUSES = {"stable", "draft", "deprecated"}
GENERATED_HEADER = "<!-- Generated by Kosmic; do not edit. -->\n"
DEFAULT_MAX_BYTES = 32768
DEFAULT_MAX_DOMAINS = 4
DEFAULT_MAX_TOPICS = 8
MAX_DOMAIN_BYTES = 6144
MAX_TOPIC_BYTES = 12288


class LibraryError(Exception):
    """Deterministic library contract failure."""


@dataclass(frozen=True)
class Document:
    metadata: dict[str, Any]
    body: str


def _parse_scalar(raw: str) -> Any:
    value = raw.strip()
    if value == "[]":
        return []
    if value.startswith("[") and value.endswith("]"):
        inner = value[1:-1].strip()
        return [] if not inner else [item.strip().strip('"\'') for item in inner.split(",")]
    if value in {"true", "false"}:
        return value == "true"
    if re.fullmatch(r"\d+", value):
        return int(value)
    return value.strip('"\'')


def parse_document(path: Path) -> Document:
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        raise LibraryError(f"{path}: missing YAML frontmatter")
    metadata: dict[str, Any] = {}
    end = None
    for index, line in enumerate(lines[1:], 1):
        if line.strip() == "---":
            end = index
            break
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            raise LibraryError(f"{path}: invalid flat frontmatter line {index + 1}")
        key, value = line.split(":", 1)
        key = key.strip()
        if not key or key in metadata:
            raise LibraryError(f"{path}: invalid or duplicate metadata key {key!r}")
        metadata[key] = _parse_scalar(value)
    if end is None:
        raise LibraryError(f"{path}: unterminated YAML frontmatter")
    return Document(metadata, "".join(lines[end + 1 :]))


def _string_list(value: Any, field: str, path: Path) -> list[str]:
    if value in (None, ""):
        return []
    if not isinstance(value, list) or any(not isinstance(item, str) or not item.strip() for item in value):
        raise LibraryError(f"{path}: {field} must be a flat non-empty string list")
    return [item.strip() for item in value]


def _required(meta: dict[str, Any], fields: Sequence[str], path: Path) -> None:
    missing = [field for field in fields if meta.get(field) in (None, "", [])]
    if missing:
        raise LibraryError(f"{path}: missing required fields: {', '.join(missing)}")


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _json_bytes(value: Any) -> bytes:
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8")


def _contained(root: Path, path: Path) -> Path:
    resolved_root = root.resolve()
    resolved = path.resolve()
    if resolved != resolved_root and resolved_root not in resolved.parents:
        raise LibraryError(f"path escapes Shared Library: {path}")
    return resolved


def _library_root(vault: Path) -> Path:
    root = vault.expanduser().resolve() / "Skills"
    if not root.is_dir():
        raise LibraryError(f"missing Shared Skill Library: {root}")
    return root


def _validate_root(path: Path) -> dict[str, Any]:
    doc = parse_document(path)
    _required(doc.metadata, ("type", "id", "status", "description"), path)
    if doc.metadata["type"] != "Shared Skill Router" or doc.metadata["id"] != "memnotes-skills":
        raise LibraryError(f"{path}: invalid Shared Skill Router identity")
    if doc.metadata["status"] != "stable":
        raise LibraryError(f"{path}: Shared Skill Router must be stable")
    if len(path.read_bytes()) > 2048:
        raise LibraryError(f"{path}: Shared Skill Router exceeds 2048 bytes")
    return doc.metadata


def _domain_entry(path: Path, root: Path) -> dict[str, Any]:
    doc = parse_document(path)
    _required(doc.metadata, ("type", "id", "status", "description", "maintainers", "triggers"), path)
    domain = str(doc.metadata["id"])
    if doc.metadata["type"] != "Domain Skill" or not ID_RE.fullmatch(domain) or "/" in domain:
        raise LibraryError(f"{path}: invalid Domain Skill identity")
    if path.parent.name != domain:
        raise LibraryError(f"{path}: domain ID must match directory name")
    if doc.metadata["status"] not in STATUSES:
        raise LibraryError(f"{path}: invalid status")
    maintainers = _string_list(doc.metadata["maintainers"], "maintainers", path)
    triggers = _string_list(doc.metadata["triggers"], "triggers", path)
    aliases = _string_list(doc.metadata.get("aliases", []), "aliases", path)
    if len(path.read_bytes()) > MAX_DOMAIN_BYTES:
        raise LibraryError(f"{path}: Domain Skill exceeds {MAX_DOMAIN_BYTES} bytes")
    return {
        "id": domain,
        "path": path.relative_to(root).as_posix(),
        "sha256": _sha(path),
        "description": str(doc.metadata["description"]),
        "maintainers": maintainers,
        "triggers": triggers,
        "aliases": aliases,
        "status": str(doc.metadata["status"]),
        "context_bytes": len(path.read_bytes()),
    }


def _topic_entry(
    path: Path,
    root: Path,
    domains: dict[str, dict[str, Any]],
    evidence_vault: Path | None = None,
) -> dict[str, Any]:
    doc = parse_document(path)
    _required(doc.metadata, ("type", "id", "domain", "audience", "status", "summary", "triggers", "source_project", "source_sha256"), path)
    topic_id = str(doc.metadata["id"])
    domain = str(doc.metadata["domain"])
    audience = str(doc.metadata["audience"])
    if doc.metadata["type"] != "Skill Topic" or not ID_RE.fullmatch(topic_id) or topic_id.count("/") != 2:
        raise LibraryError(f"{path}: invalid Skill Topic ID")
    expected = f"{domain}/{audience}/{path.stem}"
    if topic_id != expected or domain not in domains or audience not in {"usage", "development"}:
        raise LibraryError(f"{path}: topic ID/domain/audience/path mismatch")
    if "maintainers" in doc.metadata:
        raise LibraryError(f"{path}: topics cannot override Domain Skill maintainers")
    if doc.metadata["status"] not in STATUSES:
        raise LibraryError(f"{path}: invalid status")
    source_project = str(doc.metadata["source_project"])
    source_hash = str(doc.metadata["source_sha256"])
    native_source = source_project == "native" and source_hash == "empty"
    if not native_source and not SHA256_RE.fullmatch(source_hash):
        raise LibraryError(
            f"{path}: source_sha256 must be 64 lowercase hex characters, "
            "or empty when source_project is native"
        )
    size = len(path.read_bytes())
    if size > MAX_TOPIC_BYTES:
        raise LibraryError(f"{path}: Skill Topic exceeds {MAX_TOPIC_BYTES} bytes")
    evidence = _string_list(doc.metadata.get("evidence", []), "evidence", path)
    evidence_root = (evidence_vault or root.parent).resolve()
    for reference in evidence:
        candidate = (
            evidence_root / reference
            if reference.startswith("Projects/")
            else evidence_root / "Projects" / source_project / reference
        )
        resolved = candidate.resolve()
        try:
            resolved.relative_to(evidence_root)
        except ValueError as error:
            raise LibraryError(f"{path}: evidence path escapes vault: {reference}") from error
        if not resolved.exists():
            raise LibraryError(f"{path}: evidence path is missing: {reference}")
    return {
        "id": topic_id,
        "domain": domain,
        "audience": audience,
        "path": path.relative_to(root).as_posix(),
        "sha256": _sha(path),
        "title": next((line[2:].strip() for line in doc.body.splitlines() if line.startswith("# ")), path.stem),
        "summary": str(doc.metadata["summary"]),
        "triggers": _string_list(doc.metadata["triggers"], "triggers", path),
        "aliases": _string_list(doc.metadata.get("aliases", []), "aliases", path),
        "requires": _string_list(doc.metadata.get("requires", []), "requires", path),
        "evidence": evidence,
        "source_project": source_project,
        "source_sha256": source_hash,
        "status": str(doc.metadata["status"]),
        "context_bytes": size,
    }


def _validate_graph(topics: list[dict[str, Any]]) -> None:
    by_id = {row["id"]: row for row in topics}
    if len(by_id) != len(topics):
        raise LibraryError("duplicate Skill Topic ID")
    for row in topics:
        for required in row["requires"]:
            if required not in by_id:
                raise LibraryError(f"BROKEN_DEPENDENCY: {row['id']}: unknown dependency {required}")
            if required == row["id"]:
                raise LibraryError(f"BROKEN_DEPENDENCY: {row['id']}: self-dependency is forbidden")
            dependency = by_id[required]
            if dependency["status"] != "stable":
                raise LibraryError(
                    f"BROKEN_DEPENDENCY: {row['id']}: dependency on ineligible topic {required}"
                )
            if row["audience"] == "usage" and dependency["audience"] == "development":
                raise LibraryError(f"BROKEN_DEPENDENCY: Usage topic {row['id']} cannot require Development topic {required}")
    state: dict[str, int] = {}
    stack: list[str] = []

    def visit(topic_id: str) -> None:
        if state.get(topic_id) == 1:
            start = stack.index(topic_id)
            raise LibraryError("DEPENDENCY_CYCLE: " + " -> ".join(stack[start:] + [topic_id]))
        if state.get(topic_id) == 2:
            return
        state[topic_id] = 1
        stack.append(topic_id)
        for required in by_id[topic_id]["requires"]:
            visit(required)
        stack.pop()
        state[topic_id] = 2

    for topic_id in sorted(by_id):
        visit(topic_id)


def build_catalog(vault: Path, *, evidence_vault: Path | None = None) -> dict[str, Any]:
    root = _library_root(vault)
    root_metadata = _validate_root(root / "SKILL.md")
    domains: dict[str, dict[str, Any]] = {}
    for path in sorted(root.glob("*/SKILL.md")):
        entry = _domain_entry(_contained(root, path), root)
        if entry["id"] in domains:
            raise LibraryError(f"duplicate Domain Skill ID: {entry['id']}")
        domains[entry["id"]] = entry
    if not domains:
        raise LibraryError("Shared Skill Library requires at least one Domain Skill")
    topics: list[dict[str, Any]] = []
    for domain in sorted(domains):
        domain_root = root / domain
        for audience in ("development", "usage"):
            for path in sorted((domain_root / audience).glob("*.md")):
                topics.append(
                    _topic_entry(
                        _contained(root, path),
                        root,
                        domains,
                        evidence_vault=evidence_vault,
                    )
                )
    _validate_graph(topics)
    return {
        "schema": SCHEMA_VERSION,
        "library_id": str(root_metadata["id"]),
        "domains": [domains[key] for key in sorted(domains)],
        "topics": sorted(topics, key=lambda row: row["id"]),
    }


def _domain_index(domain: dict[str, Any], topics: Sequence[dict[str, Any]]) -> bytes:
    rows = [GENERATED_HEADER, f"# {domain['id']} Topics\n\n", "| ID | Audience | Summary |\n", "|---|---|---|\n"]
    for row in sorted((item for item in topics if item["domain"] == domain["id"]), key=lambda item: item["id"]):
        rows.append(f"| `{row['id']}` | {row['audience']} | {row['summary']} |\n")
    return "".join(rows).encode("utf-8")


def _generated_payloads(
    vault: Path, *, evidence_vault: Path | None = None
) -> dict[str, bytes]:
    root = _library_root(vault)
    catalog = build_catalog(vault, evidence_vault=evidence_vault)
    catalog_bytes = _json_bytes(catalog)
    indexes = {f"{domain['id']}/index.md": _domain_index(domain, catalog["topics"]) for domain in catalog["domains"]}
    policy = parse_document(root / "SKILL.md").metadata
    manifest = {
        "schema": SCHEMA_VERSION,
        "generator_version": GENERATOR_VERSION,
        "library_id": catalog["library_id"],
        "root_sha256": _sha(root / "SKILL.md"),
        "catalog_sha256": hashlib.sha256(catalog_bytes).hexdigest(),
        "policy": {
            "max_packet_bytes": int(policy.get("max_packet_bytes", DEFAULT_MAX_BYTES)),
            "max_domains": int(policy.get("max_domains", DEFAULT_MAX_DOMAINS)),
            "max_topics": int(policy.get("max_topics", DEFAULT_MAX_TOPICS)),
        },
        "domains": [{"id": row["id"], "sha256": row["sha256"]} for row in catalog["domains"]],
    }
    return {".kosmic/catalog.json": catalog_bytes, ".kosmic/manifest.json": _json_bytes(manifest), **indexes}


def _replace_generated(root: Path, staging: Path, relative_paths: Sequence[str]) -> None:
    backup = Path(tempfile.mkdtemp(prefix="kosmic-library-backup-", dir=root.parent))
    replaced: list[str] = []
    try:
        for relative in relative_paths:
            target = root / relative
            source = staging / relative
            if target.exists():
                saved = backup / relative
                saved.parent.mkdir(parents=True, exist_ok=True)
                os.replace(target, saved)
            target.parent.mkdir(parents=True, exist_ok=True)
            os.replace(source, target)
            replaced.append(relative)
    except Exception:
        for relative in reversed(replaced):
            (root / relative).unlink(missing_ok=True)
        for saved in sorted(backup.rglob("*")):
            if saved.is_file():
                target = root / saved.relative_to(backup)
                target.parent.mkdir(parents=True, exist_ok=True)
                os.replace(saved, target)
        raise
    finally:
        shutil.rmtree(backup, ignore_errors=True)


def generate_library(vault: Path) -> tuple[Path, ...]:
    root = _library_root(vault)
    payloads = _generated_payloads(vault)
    staging = Path(tempfile.mkdtemp(prefix="kosmic-library-stage-", dir=root.parent))
    try:
        for relative, content in payloads.items():
            path = staging / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        _replace_generated(root, staging, sorted(payloads))
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    validate_library(vault)
    return tuple(root / relative for relative in sorted(payloads))


def validate_library(vault: Path) -> None:
    root = _library_root(vault)
    expected = _generated_payloads(vault)
    for relative, content in expected.items():
        path = root / relative
        if not path.is_file():
            raise LibraryError(f"STALE_LIBRARY: stale generated artifact is missing: {relative}")
        if path.read_bytes() != content:
            raise LibraryError(f"STALE_LIBRARY: stale generated drift: {relative}")


def _load_generated(vault: Path) -> tuple[Path, dict[str, Any], dict[str, Any]]:
    root = _library_root(vault)
    validate_library(vault)
    catalog = json.loads((root / ".kosmic/catalog.json").read_text(encoding="utf-8"))
    manifest = json.loads((root / ".kosmic/manifest.json").read_text(encoding="utf-8"))
    return root, catalog, manifest


def _normalize(value: str) -> str:
    return " ".join(re.findall(r"[a-z0-9]+", unicodedata.normalize("NFKC", value).casefold()))


def _score(row: dict[str, Any], query: str, project: str | None) -> tuple[int, list[str]]:
    q = _normalize(query)
    tokens = set(q.split())
    score = 0
    trace: list[str] = []
    fields = [(row["id"], 100), *[(value, 80) for value in row["triggers"]], *[(value, 70) for value in row["aliases"]], (row["title"], 40), (row["summary"], 20)]
    for value, weight in fields:
        normalized = _normalize(value)
        if q == normalized:
            score += weight * 4
            trace.append(f"exact:{weight}:{value}")
        elif q in normalized or normalized in q:
            score += weight * 2
            trace.append(f"phrase:{weight}:{value}")
        else:
            overlap = len(tokens & set(normalized.split()))
            if overlap:
                score += weight * overlap
                trace.append(f"tokens:{weight}x{overlap}:{value}")
    if project and row["domain"] == project:
        score += 15
        trace.append("project-domain:+15")
    return score, trace


def _dependency_order(selected: Iterable[str], by_id: dict[str, dict[str, Any]]) -> list[str]:
    ordered: list[str] = []
    seen: set[str] = set()
    def visit(topic_id: str) -> None:
        if topic_id in seen:
            return
        seen.add(topic_id)
        for required in sorted(by_id[topic_id]["requires"]):
            visit(required)
        ordered.append(topic_id)
    for topic_id in sorted(selected):
        visit(topic_id)
    return ordered


def _plan_hash(plan: dict[str, Any]) -> str:
    return hashlib.sha256(_json_bytes({key: value for key, value in plan.items() if key != "plan_sha256"})).hexdigest()


def resolve_library(
    vault: Path,
    *,
    query: str | None = None,
    route: str | None = None,
    role: str = "auto",
    project: str | None = None,
    max_bytes: int | None = None,
    max_domains: int | None = None,
    max_topics: int | None = None,
) -> dict[str, Any]:
    if bool(query) == bool(route):
        raise LibraryError("resolve-library requires exactly one of query or route")
    if role not in ROLES:
        raise LibraryError(f"invalid role: {role}")
    root, catalog, manifest = _load_generated(vault)
    eligible = [row for row in catalog["topics"] if row["status"] == "stable" and (role == "auto" or row["audience"] == role)]
    exclusions = [
        {
            "id": row["id"],
            "reason": (
                f"status:{row['status']}"
                if row["status"] != "stable"
                else f"audience:{row['audience']}"
            ),
        }
        for row in catalog["topics"]
        if row not in eligible
    ]
    traces: list[str] = []
    selected_domain_ids: list[str] = []
    if route:
        matches = [row for row in eligible if row["id"] == route]
        if matches:
            selected = [matches[0]["id"]]
            traces.append(f"exact-route:{route}")
        elif route in {row["id"] for row in catalog["domains"]}:
            selected = []
            selected_domain_ids = [route]
            traces.append(f"exact-domain-route:{route}")
        else:
            raise LibraryError(f"NO_MATCH: {route}")
    else:
        scored = [(score, row, trace) for row in eligible for score, trace in [_score(row, query or "", project)] if score > 0]
        if not scored:
            raise LibraryError("NO_MATCH: no eligible topic")
        best = max(score for score, _, _ in scored)
        winners = sorted((row for score, row, _ in scored if score == best), key=lambda row: row["id"])
        if len(winners) != 1:
            raise LibraryError("AMBIGUOUS: " + ", ".join(row["id"] for row in winners[:5]))
        selected = [winners[0]["id"]]
        traces.extend(f"{winners[0]['id']}:{item}" for score, row, trace in scored if row["id"] == winners[0]["id"] for item in trace)
    by_id = {row["id"]: row for row in catalog["topics"]}
    ordered_ids = _dependency_order(selected, by_id)
    ordered = [by_id[topic_id] for topic_id in ordered_ids]
    domains_by_id = {row["id"]: row for row in catalog["domains"]}
    domain_ids = sorted(
        {*selected_domain_ids, *(row["domain"] for row in ordered)}
    )
    domains = [domains_by_id[domain] for domain in domain_ids]
    policy = manifest["policy"]
    byte_limit = min(int(max_bytes or policy["max_packet_bytes"]), int(policy["max_packet_bytes"]))
    domain_limit = min(int(max_domains or policy["max_domains"]), int(policy["max_domains"]))
    topic_limit = min(int(max_topics or policy["max_topics"]), int(policy["max_topics"]))
    chunks = [
        *(
            _packet_chunk("domain", row, (root / row["path"]).read_text(encoding="utf-8"))
            for row in domains
        ),
        *(
            _packet_chunk("topic", row, (root / row["path"]).read_text(encoding="utf-8"))
            for row in ordered
        ),
    ]
    total = len("\n".join(chunks).encode("utf-8"))
    if total > byte_limit or len(domains) > domain_limit or len(ordered) > topic_limit:
        raise LibraryError(f"BUDGET_EXCEEDED: bytes {total}/{byte_limit}, domains {len(domains)}/{domain_limit}, topics {len(ordered)}/{topic_limit}")
    plan: dict[str, Any] = {
        "schema": SCHEMA_VERSION,
        "request": {"query": query or "", "route": route or "", "role": role, "project": project or "", "max_bytes": byte_limit, "max_domains": domain_limit, "max_topics": topic_limit},
        "manifest_sha256": _sha(root / ".kosmic/manifest.json"),
        "domains": [{key: row[key] for key in ("id", "path", "sha256", "context_bytes")} for row in domains],
        "topics": [{key: row[key] for key in ("id", "path", "sha256", "context_bytes")} for row in ordered],
        "ordered_loads": [*(f"domain:{row['id']}" for row in domains), *(f"topic:{row['id']}" for row in ordered)],
        "total_bytes": total,
        "trace": traces + [f"dependency:{topic_id}" for topic_id in ordered_ids if topic_id not in selected],
        "exclusions": exclusions,
    }
    plan["plan_sha256"] = _plan_hash(plan)
    return plan


def _packet_chunk(kind: str, row: dict[str, Any], content: str) -> str:
    return f"<!-- {kind}:{row['id']} sha256:{row['sha256']} -->\n{content.rstrip()}\n"


def load_recipe_packet(vault: Path, plan: dict[str, Any]) -> str:
    root, _, _ = _load_generated(vault)
    if plan.get("schema") != SCHEMA_VERSION or plan.get("plan_sha256") != _plan_hash(plan):
        raise LibraryError("INVALID_PLAN: plan hash mismatch")
    if plan.get("manifest_sha256") != _sha(root / ".kosmic/manifest.json"):
        raise LibraryError("INVALID_PLAN: stale library manifest hash")
    chunks: list[str] = []
    for kind in ("domains", "topics"):
        for row in plan.get(kind, []):
            path = _contained(root, root / str(row["path"]))
            if not path.is_file() or _sha(path) != row["sha256"]:
                raise LibraryError(f"INVALID_PLAN: stale source hash for {row.get('id')}")
            content = path.read_text(encoding="utf-8")
            if len(content.encode("utf-8")) != row["context_bytes"]:
                raise LibraryError(f"INVALID_PLAN: byte cost mismatch for {row.get('id')}")
            chunks.append(_packet_chunk(kind[:-1], row, content))
    packet = "\n".join(chunks)
    if len(packet.encode("utf-8")) != plan.get("total_bytes"):
        raise LibraryError("INVALID_PLAN: total byte cost mismatch")
    return packet


def migrate_assignments(vault: Path, project: Path, assignments: dict[str, str]) -> dict[str, Any]:
    root = _library_root(vault)
    project = project.expanduser().resolve()
    references = sorted(path for path in (project / "skills").glob("*/references/**/*.md") if path.is_file())
    keys = [path.relative_to(project / "skills").as_posix() for path in references]
    missing = sorted(set(keys) - set(assignments))
    extra = sorted(set(assignments) - set(keys))
    if missing or extra:
        raise LibraryError(f"migration assignments unassigned={missing} unknown={extra}")
    staging = Path(tempfile.mkdtemp(prefix="kosmic-migration-", dir=root.parent))
    shutil.copytree(root, staging / "Skills", dirs_exist_ok=True)
    staged_root = staging / "Skills"
    migrations: list[dict[str, Any]] = []
    try:
        for source, key in zip(references, keys):
            target_id = assignments[key]
            if not ID_RE.fullmatch(target_id) or target_id.count("/") != 2:
                raise LibraryError(f"invalid migration target: {target_id}")
            domain, audience, slug = target_id.split("/")
            if not (staged_root / domain / "SKILL.md").is_file():
                raise LibraryError(f"migration target domain does not exist: {domain}")
            document = parse_document(source)
            source_audience = str(document.metadata.get("audience") or "")
            if source_audience not in {audience, "both"}:
                raise LibraryError(
                    f"{source}: audience {source_audience!r} does not permit target audience {audience!r}"
                )
            target = staged_root / domain / audience / f"{slug}.md"
            if target.exists():
                raise LibraryError(f"migration collision: {target_id}")
            source_hash = str(document.metadata.get("source_sha256") or "")
            if not SHA256_RE.fullmatch(source_hash):
                raise LibraryError(f"{source}: missing or invalid source_sha256")
            source_reference = str(document.metadata.get("source") or "")
            authoritative = (project / source_reference).resolve()
            try:
                authoritative.relative_to(project)
            except ValueError as error:
                raise LibraryError(f"{source}: source path escapes Project") from error
            if not authoritative.is_file() or _sha(authoritative) != source_hash:
                raise LibraryError(f"{source}: stale or missing authoritative source {source_reference}")
            authoritative_document = parse_document(authoritative)
            evidence = _string_list(
                authoritative_document.metadata.get("evidence", []),
                "evidence",
                authoritative,
            )
            summary = next((line[2:].strip() for line in document.body.splitlines() if line.startswith("# ")), slug)
            metadata = [
                "---", "type: Skill Topic", f"id: {target_id}", f"domain: {domain}", f"audience: {audience}", "status: stable",
                f"summary: {summary}", f"triggers: [{summary}]", "aliases: []", "requires: []", f"evidence: [{', '.join(evidence)}]",
                f"source_project: {project.name}", f"source_sha256: {source_hash}", "---", "",
            ]
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text("\n".join(metadata) + document.body, encoding="utf-8")
            migrations.append({"source": key, "target": target_id, "source_sha256": source_hash, "evidence": evidence})
        staged_vault = staging
        payloads = _generated_payloads(staged_vault, evidence_vault=vault)
        for relative, content in payloads.items():
            path = staged_root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        if any((staged_root / relative).read_bytes() != content for relative, content in payloads.items()):
            raise LibraryError("migration staged generated-byte verification failed")
        backup = root.parent / f".Skills-backup-{os.getpid()}"
        os.replace(root, backup)
        try:
            os.replace(staged_root, root)
        except Exception:
            os.replace(backup, root)
            raise
        shutil.rmtree(backup, ignore_errors=True)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return {"schema": SCHEMA_VERSION, "project": project.name, "migrations": migrations}


def _router_payload(vault: Path) -> dict[str, bytes]:
    root = _library_root(vault)
    manifest_path = root / ".kosmic/manifest.json"
    manifest_hash = _sha(manifest_path)
    policy = json.loads(manifest_path.read_text(encoding="utf-8"))["policy"]
    cli = Path(__file__).resolve().with_name("kosmic_project_skills.py")
    command = f'python3 "{cli}"'
    router = (
        "---\n"
        "name: memnotes-skills\n"
        "description: Resolve and load bounded procedures from the Memnotes Shared Skill Library.\n"
        "---\n\n"
        "# Memnotes Shared Skills\n\n"
        "Use this router for maintained technical procedures. Do not scan the vault or load every domain.\n\n"
        f"1. Run `{command} resolve-library --vault \"{vault.expanduser().resolve()}\"` with exactly one query or route and the task role.\n"
        "2. Inspect ambiguity, exclusions, dependencies, and byte cost in the returned plan; save the unchanged JSON.\n"
        f"3. Run `{command} load-library --vault \"{vault.expanduser().resolve()}\" --plan PLAN.json`.\n"
        "4. Follow the emitted Domain Skill and topic packet. Never omit required dependencies or silently truncate a topic.\n\n"
        f"Library budget policy: {policy['max_packet_bytes']} packet bytes, {policy['max_domains']} domains, {policy['max_topics']} topics; requests are clamped to these maxima.\n"
        f"Authoritative library: `{root}`\n"
        f"Manifest SHA-256 at publication: `{manifest_hash}`\n"
        "Failure is closed: stale hashes, ambiguity, missing dependencies, cycles, and budget overflow return no recipe bodies.\n"
    ).encode("utf-8")
    identity = _json_bytes(
        {
            "schema": SCHEMA_VERSION,
            "library_id": "memnotes-skills",
            "manifest_sha256": manifest_hash,
            "vault": str(vault.expanduser().resolve()),
        }
    )
    return {"SKILL.md": router, ".kosmic-library-router.json": identity}


def _canonical_router(vault: Path) -> Path:
    return _library_root(vault) / ".kosmic/router"


def generate_router(vault: Path) -> Path:
    validate_library(vault)
    destination = _canonical_router(vault)
    staging = Path(tempfile.mkdtemp(prefix="kosmic-router-stage-", dir=destination.parent))
    try:
        for relative, content in _router_payload(vault).items():
            path = staging / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        backup = destination.parent / f".router-backup-{os.getpid()}"
        if destination.exists():
            os.replace(destination, backup)
        try:
            os.replace(staging, destination)
        except Exception:
            if backup.exists():
                os.replace(backup, destination)
            raise
        shutil.rmtree(backup, ignore_errors=True)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return destination


def _router_matches(vault: Path, path: Path) -> bool:
    if not path.is_dir():
        return False
    expected = _router_payload(vault)
    return all((path / relative).is_file() and (path / relative).read_bytes() == content for relative, content in expected.items())


def install_shared_router(vault: Path, destination_root: Path) -> Path:
    source = generate_router(vault)
    destination_root = destination_root.expanduser().resolve()
    destination_root.mkdir(parents=True, exist_ok=True)
    destination = destination_root / "memnotes-skills"
    identity = destination / ".kosmic-library-router.json"
    if destination.exists() and not identity.is_file():
        raise LibraryError(f"INSTALLATION_COLLISION: installation collision at unmanaged path: {destination}")
    managed_pairs = sorted(
        path for path in destination_root.iterdir()
        if path.is_dir() and (path / ".kosmic-projection.json").is_file()
    )
    staging = Path(tempfile.mkdtemp(prefix=".memnotes-skills-stage-", dir=destination_root))
    shutil.copytree(source, staging, dirs_exist_ok=True)
    backup = Path(tempfile.mkdtemp(prefix=".memnotes-skills-backup-", dir=destination_root))
    moved: list[tuple[Path, Path]] = []
    installed = False
    try:
        for old in [destination, *managed_pairs]:
            if old.exists():
                saved = backup / old.name
                os.replace(old, saved)
                moved.append((saved, old))
        os.replace(staging, destination)
        installed = True
        if not _router_matches(vault, destination):
            raise LibraryError("installed Shared Skill Router failed byte verification")
    except Exception:
        if installed:
            shutil.rmtree(destination, ignore_errors=True)
        for saved, old in reversed(moved):
            if saved.exists():
                os.replace(saved, old)
        raise
    finally:
        shutil.rmtree(staging, ignore_errors=True)
        shutil.rmtree(backup, ignore_errors=True)
    return destination


def check_shared_router_installation(vault: Path, destination_root: Path) -> Path:
    destination = destination_root.expanduser().resolve() / "memnotes-skills"
    if not _router_matches(vault, destination):
        raise LibraryError(f"Shared Skill Router is missing or stale: {destination}")
    stale_pairs = [
        path.name for path in destination.parent.iterdir()
        if path.is_dir() and (path / ".kosmic-projection.json").is_file()
    ]
    if stale_pairs:
        raise LibraryError("managed Project Skill Pairs remain installed: " + ", ".join(sorted(stale_pairs)))
    return destination
