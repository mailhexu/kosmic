SCHEMA_VERSION = "kosmic.shared-library/v2"
GENERATOR_VERSION = 2
ID_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*(?:/(?:usage|development)/[a-z0-9]+(?:-[a-z0-9]+)*)?$")
SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
ROLES = {"usage", "development", "auto"}
STATUSES = {"stable", "draft", "deprecated"}
ARTIFACT_ROLES = {"procedure", "guideline", "knowledge", "evidence"}
INTENTS = {"do", "check", "understand", "investigate"}
RELATION_ROLES = {
    "requires_procedures": "procedure",
    "governed_by": "guideline",
    "uses_knowledge": "knowledge",
    "supported_by": "evidence",
    "supersedes": "evidence",
}
PROCEDURE_SECTIONS = {
    "when to use", "preconditions", "procedure", "decisions and branches",
    "verification", "failure handling", "references",
}
GENERATED_HEADER = "<!-- Generated by Kosmic; do not edit. -->\n"
DEFAULT_MAX_BYTES = 32768
DEFAULT_MAX_DOMAINS = 4
DEFAULT_MAX_TOPICS = 8
MAX_DOMAIN_BYTES = 6144
MAX_TOPIC_BYTES = 12288


class LibraryError(Exception):
    """Deterministic library contract failure."""


@dataclass(frozen=True)
class Document:
    metadata: dict[str, Any]
    body: str


def parse_document(path: Path) -> Document:
    return parse_document_text(path.read_text(encoding="utf-8"), path)


def parse_document_text(text: str, path: Path) -> Document:
    """Parse captured bytes without reopening an already verified source path."""
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        raise LibraryError(f"{path}: missing YAML frontmatter")
    end = None
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            end = index
            break
    if end is None:
        raise LibraryError(f"{path}: unterminated YAML frontmatter")
    try:
        metadata = parse_mapping("".join(lines[1:end]), context=str(path))
    except YAMLParseError as error:
        raise LibraryError(str(error)) from error
    return Document(metadata, "".join(lines[end + 1 :]))


def _string_list(value: Any, field: str, path: Path) -> list[str]:
    if value in (None, ""):
        return []
    if not isinstance(value, list) or any(not isinstance(item, str) or not item.strip() for item in value):
        raise LibraryError(f"{path}: {field} must be a flat non-empty string list")
    return [item.strip() for item in value]


def _required(meta: dict[str, Any], fields: Sequence[str], path: Path) -> None:
    missing = [field for field in fields if meta.get(field) in (None, "", [])]
    if missing:
        raise LibraryError(f"{path}: missing required fields: {', '.join(missing)}")


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _json_bytes(value: Any) -> bytes:
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8")


def _contained(root: Path, path: Path) -> Path:
    resolved_root = root.resolve()
    resolved = path.resolve()
    if resolved != resolved_root and resolved_root not in resolved.parents:
        raise LibraryError(f"path escapes Shared Library: {path}")
    return resolved


def _library_root(vault: Path) -> Path:
    root = vault.expanduser().resolve() / "Skills"
    if not root.is_dir():
        raise LibraryError(f"missing Shared Skill Library: {root}")
    return root

def _authorize_library_mutation(vault: Path, work_record: str | None, purpose: str) -> None:
    if not isinstance(work_record, str) or not work_record.strip():
        try:
            from .kosmic_work import WorkdirError
        except ImportError:
            from kosmic_work import WorkdirError  # type: ignore[no-redef]
        raise WorkdirError("WORK_RECORD_REQUIRED", f"{purpose} requires --work-record")
    try:
        from . import kosmic_work
    except ImportError:
        import kosmic_work  # type: ignore[no-redef]
    project_id = work_record.strip().split("/", 1)[0]
    project_root = Path(vault).expanduser().resolve() / "Projects" / project_id
    kosmic_work.resolve_work_record(project_root, work_record.strip())


def _validate_root(path: Path) -> dict[str, Any]:
    doc = parse_document(path)
    _required(doc.metadata, ("type", "id", "status", "description"), path)
    if doc.metadata["type"] != "Shared Skill Router" or doc.metadata["id"] != "memnotes-skills":
        raise LibraryError(f"{path}: invalid Shared Skill Router identity")
    if doc.metadata["status"] != "stable":
        raise LibraryError(f"{path}: Shared Skill Router must be stable")
    if len(path.read_bytes()) > 2048:
        raise LibraryError(f"{path}: Shared Skill Router exceeds 2048 bytes")
    return doc.metadata


def _domain_entry(path: Path, root: Path) -> dict[str, Any]:
    doc = parse_document(path)
    _required(doc.metadata, ("type", "id", "status", "description", "maintainers", "triggers"), path)
    domain = str(doc.metadata["id"])
    if doc.metadata["type"] != "Domain Skill" or not ID_RE.fullmatch(domain) or "/" in domain:
        raise LibraryError(f"{path}: invalid Domain Skill identity")
    if path.parent.name != domain:
        raise LibraryError(f"{path}: domain ID must match directory name")
    if doc.metadata["status"] not in STATUSES:
        raise LibraryError(f"{path}: invalid status")
    maintainers = _string_list(doc.metadata["maintainers"], "maintainers", path)
    triggers = _string_list(doc.metadata["triggers"], "triggers", path)
    aliases = _string_list(doc.metadata.get("aliases", []), "aliases", path)
    if len(path.read_bytes()) > MAX_DOMAIN_BYTES:
        raise LibraryError(f"{path}: Domain Skill exceeds {MAX_DOMAIN_BYTES} bytes")
    return {
        "id": domain,
        "path": path.relative_to(root).as_posix(),
        "sha256": _sha(path),
        "description": str(doc.metadata["description"]),
        "maintainers": maintainers,
        "triggers": triggers,
        "aliases": aliases,
        "status": str(doc.metadata["status"]),
        "context_bytes": len(path.read_bytes()),
    }


def _topic_entry(
    path: Path,
    root: Path,
    domains: dict[str, dict[str, Any]],
    evidence_vault: Path | None = None,
) -> dict[str, Any]:
    doc = parse_document(path)
    _required(
        doc.metadata,
        ("type", "id", "domain", "audience", "artifact_role", "status",
         "summary", "triggers", "source_project", "source_sha256"),
        path,
    )
    topic_id = str(doc.metadata["id"])
    domain = str(doc.metadata["domain"])
    audience = str(doc.metadata["audience"])
    artifact_role = str(doc.metadata["artifact_role"])
    if doc.metadata["type"] != "Domain Topic" or not ID_RE.fullmatch(topic_id) or topic_id.count("/") != 2:
        raise LibraryError(f"{path}: invalid Domain Topic ID")
    expected = f"{domain}/{audience}/{path.stem}"
    if topic_id != expected or domain not in domains or audience not in {"usage", "development"}:
        raise LibraryError(f"{path}: topic ID/domain/audience/path mismatch")
    if artifact_role not in ARTIFACT_ROLES:
        raise LibraryError(f"{path}: invalid artifact_role {artifact_role!r}")
    if "maintainers" in doc.metadata:
        raise LibraryError(f"{path}: topics cannot override Domain Skill maintainers")
    if doc.metadata["status"] not in STATUSES:
        raise LibraryError(f"{path}: invalid status")
    if "requires" in doc.metadata:
        raise LibraryError(f"{path}: obsolete requires field is forbidden")
    if artifact_role == "procedure":
        _required(doc.metadata, ("outcome",), path)
        sections: dict[str, list[str]] = {}
        current: str | None = None
        for line in doc.body.splitlines():
            if line.startswith("## "):
                current = line[3:].strip().casefold()
                sections.setdefault(current, [])
            elif current is not None:
                sections[current].append(line)
        required_headings = PROCEDURE_SECTIONS
        missing = sorted(
            heading
            for heading in required_headings
            if heading not in sections
            or not any(line.strip() for line in sections[heading])
        )
        if missing:
            raise LibraryError(
                f"{path}: procedure missing required non-empty section(s): "
                + ", ".join(missing)
            )
    observed_on = str(doc.metadata.get("observed_on") or "")
    if artifact_role == "evidence":
        if not DATE_RE.fullmatch(observed_on):
            raise LibraryError(f"{path}: evidence observed_on must be YYYY-MM-DD")
    elif observed_on:
        raise LibraryError(f"{path}: observed_on is valid only for evidence")
    source_project = str(doc.metadata["source_project"])
    source_hash = str(doc.metadata["source_sha256"])
    native_source = source_project == "native" and source_hash == "empty"
    if not native_source and not SHA256_RE.fullmatch(source_hash):
        raise LibraryError(f"{path}: source_sha256 must be 64 lowercase hex characters, or empty when source_project is native")
    size = len(path.read_bytes())
    if size > MAX_TOPIC_BYTES:
        raise LibraryError(f"{path}: Domain Topic exceeds {MAX_TOPIC_BYTES} bytes")
    evidence = _string_list(doc.metadata.get("evidence", []), "evidence", path)
    uses_routines = _string_list(doc.metadata.get("uses_routines", []), "uses_routines", path)
    if artifact_role != "procedure" and uses_routines:
        raise LibraryError(f"{path}: uses_routines is valid only for procedures")
    evidence_root = (evidence_vault or root.parent).resolve()
    for reference in evidence:
        candidate = evidence_root / reference if reference.startswith("Projects/") else evidence_root / "Projects" / source_project / reference
        resolved = candidate.resolve()
        try:
            resolved.relative_to(evidence_root)
        except ValueError as error:
            raise LibraryError(f"{path}: evidence path escapes vault: {reference}") from error
        if not resolved.exists():
            raise LibraryError(f"{path}: evidence path is missing: {reference}")
    row = {
        "id": topic_id, "domain": domain, "audience": audience,
        "artifact_role": artifact_role, "path": path.relative_to(root).as_posix(),
        "sha256": _sha(path),
        "title": next((line[2:].strip() for line in doc.body.splitlines() if line.startswith("# ")), path.stem),
        "summary": str(doc.metadata["summary"]),
        "triggers": _string_list(doc.metadata["triggers"], "triggers", path),
        "aliases": _string_list(doc.metadata.get("aliases", []), "aliases", path),
        "outcome": str(doc.metadata.get("outcome") or ""),
        "observed_on": observed_on,
        "evidence": evidence, "source_project": source_project,
        "source_sha256": source_hash, "status": str(doc.metadata["status"]),
        "context_bytes": size,
        "uses_routines": sorted(set(uses_routines)),
    }
    for field in RELATION_ROLES:
        row[field] = _string_list(doc.metadata.get(field, []), field, path)
    return row


def _validate_graph(topics: list[dict[str, Any]]) -> None:
    by_id = {row["id"]: row for row in topics}
    if len(by_id) != len(topics):
        raise LibraryError("duplicate Domain Topic ID")
    for row in topics:
        for field, target_role in RELATION_ROLES.items():
            for target in row[field]:
                if target not in by_id:
                    raise LibraryError(f"BROKEN_DEPENDENCY: {row['id']}: unknown dependency {target}")
                if target == row["id"]:
                    raise LibraryError(f"BROKEN_DEPENDENCY: {row['id']}: self-dependency is forbidden")
                dependency = by_id[target]
                if dependency["status"] != "stable":
                    raise LibraryError(f"BROKEN_DEPENDENCY: {row['id']}: dependency on ineligible topic {target}")
                if dependency["artifact_role"] != target_role:
                    raise LibraryError(
                        f"BROKEN_DEPENDENCY: {row['id']}: {field} target {target} "
                        f"must have artifact_role {target_role}"
                    )
                if row["audience"] == "usage" and dependency["audience"] == "development":
                    raise LibraryError(f"BROKEN_DEPENDENCY: Usage topic {row['id']} cannot require Development topic {target}")
                if field == "supersedes":
                    if row["artifact_role"] != "evidence":
                        raise LibraryError(f"BROKEN_DEPENDENCY: {row['id']}: only evidence may supersede evidence")
                    if row["observed_on"] <= dependency["observed_on"]:
                        raise LibraryError(f"BROKEN_DEPENDENCY: {row['id']}: supersedes must point to older evidence")
    state: dict[str, int] = {}
    stack: list[str] = []
    def visit(topic_id: str) -> None:
        if state.get(topic_id) == 1:
            start = stack.index(topic_id)
            raise LibraryError("DEPENDENCY_CYCLE: " + " -> ".join(stack[start:] + [topic_id]))
        if state.get(topic_id) == 2:
            return
        state[topic_id] = 1
        stack.append(topic_id)
        for field in RELATION_ROLES:
            for target in by_id[topic_id][field]:
                visit(target)
        stack.pop()
        state[topic_id] = 2
    for topic_id in sorted(by_id):
        visit(topic_id)


def build_catalog(vault: Path, *, evidence_vault: Path | None = None) -> dict[str, Any]:
    root = _library_root(vault)
    root_metadata = _validate_root(root / "SKILL.md")
    domains: dict[str, dict[str, Any]] = {}
    for path in sorted(root.glob("*/SKILL.md")):
        entry = _domain_entry(_contained(root, path), root)
        if entry["id"] in domains:
            raise LibraryError(f"duplicate Domain Skill ID: {entry['id']}")
        domains[entry["id"]] = entry
    if not domains:
        raise LibraryError("Shared Skill Library requires at least one Domain Skill")
    topics: list[dict[str, Any]] = []
    for domain in sorted(domains):
        domain_root = root / domain
        for audience in ("development", "usage"):
            for path in sorted((domain_root / audience).glob("*.md")):
                topics.append(
                    _topic_entry(
                        _contained(root, path),
                        root,
                        domains,
                        evidence_vault=evidence_vault,
                    )
                )
    _validate_graph(topics)
    return {
        "schema": SCHEMA_VERSION,
        "library_id": str(root_metadata["id"]),
        "domains": [domains[key] for key in sorted(domains)],
        "topics": sorted(topics, key=lambda row: row["id"]),
    }


def _domain_index(domain: dict[str, Any], topics: Sequence[dict[str, Any]]) -> bytes:
    rows = [GENERATED_HEADER, f"# {domain['id']} Topics\n\n", "| ID | Audience | Summary |\n", "|---|---|---|\n"]
    for row in sorted((item for item in topics if item["domain"] == domain["id"]), key=lambda item: item["id"]):
        rows.append(f"| `{row['id']}` | {row['audience']} | {row['summary']} |\n")
    return "".join(rows).encode("utf-8")

def _validate_routine_edges(
    routines: dict[str, object], catalog: dict[str, object]
) -> None:
    routine_by_id = {str(row["id"]): row for row in routines["routines"]}
    for topic in catalog["topics"]:
        for routine_id in topic["uses_routines"]:
            if routine_id not in routine_by_id:
                raise LibraryError(
                    f"BROKEN_ROUTINE: {topic['id']}: unknown routine {routine_id}"
                )
    catalog_domains = {str(row["id"]) for row in catalog["domains"]}
    for routine_id, routine in routine_by_id.items():
        for topic_id in routine["procedures"]:
            if str(topic_id).split("/", 1)[0] not in catalog_domains:
                raise LibraryError(
                    f"BROKEN_ROUTINE: {routine_id}: procedure is outside active catalog domain: {topic_id}"
                )
        declared = sorted(routine["procedures"])
        expected = sorted(
            topic["id"]
            for topic in catalog["topics"]
            if routine_id in topic["uses_routines"]
        )
        if declared != expected:
            raise LibraryError(
                f"BROKEN_ROUTINE: reciprocal procedure edges differ for {routine_id}"
            )


def _generated_payloads(
    vault: Path, *, evidence_vault: Path | None = None, source_root: Path | None = None
) -> dict[str, bytes]:
    root = _library_root(vault)
    source = (source_root or Path(__file__).resolve().parent).resolve()
    repo = source.parent.parent
    routines = build_routine_inventory(repo, source, root)
    catalog = build_catalog(vault, evidence_vault=evidence_vault)
    _validate_routine_edges(routines, catalog)
    catalog_bytes = _json_bytes(catalog)
    indexes = {f"{domain['id']}/index.md": _domain_index(domain, catalog["topics"]) for domain in catalog["domains"]}
    routine_bytes = _json_bytes(routines)
    policy = parse_document(root / "SKILL.md").metadata
    manifest = {
        "schema": SCHEMA_VERSION,
        "generator_version": GENERATOR_VERSION,
        "library_id": catalog["library_id"],
        "root_sha256": _sha(root / "SKILL.md"),
        "catalog_sha256": hashlib.sha256(catalog_bytes).hexdigest(),
        "routine_inventory_sha256": hashlib.sha256(routine_bytes).hexdigest(),
        "policy": {
            "max_packet_bytes": int(policy.get("max_packet_bytes", DEFAULT_MAX_BYTES)),
            "max_domains": int(policy.get("max_domains", DEFAULT_MAX_DOMAINS)),
            "max_topics": int(policy.get("max_topics", DEFAULT_MAX_TOPICS)),
        },
        "domains": [{"id": row["id"], "sha256": row["sha256"]} for row in catalog["domains"]],
    }
    return {
        ".kosmic/catalog.json": catalog_bytes,
        ".kosmic/routines.json": routine_bytes,
        ".kosmic/manifest.json": _json_bytes(manifest),
        **indexes,
    }




def generate_library(vault: Path, source_root: Path | None = None, *,
                     work_record: str | None = None) -> tuple[Path, ...]:
    _authorize_library_mutation(vault, work_record, "generate-library")
    root = _library_root(vault)
    payloads = _generated_payloads(vault, source_root=source_root)
    staging = Path(tempfile.mkdtemp(prefix="kosmic-library-stage-", dir=root.parent))
    try:
        for relative, content in payloads.items():
            path = staging / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        publish_tree(staging, root, sorted(payloads))
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    validate_library(vault, source_root=source_root)
    return tuple(root / relative for relative in sorted(payloads))


def validate_library(vault: Path, source_root: Path | None = None) -> None:
    root = _library_root(vault)
    expected = _generated_payloads(vault, source_root=source_root)
    for relative, content in expected.items():
        path = root / relative
        if not path.is_file():
            raise LibraryError(f"STALE_LIBRARY: stale generated artifact is missing: {relative}")
        if path.read_bytes() != content:
            raise LibraryError(f"STALE_LIBRARY: stale generated drift: {relative}")


def _load_generated(vault: Path) -> tuple[Path, dict[str, Any], dict[str, Any]]:
    root = _library_root(vault)
    validate_library(vault)
    catalog = json.loads((root / ".kosmic/catalog.json").read_text(encoding="utf-8"))
    manifest = json.loads((root / ".kosmic/manifest.json").read_text(encoding="utf-8"))
    return root, catalog, manifest


def _normalize(value: str) -> str:
    return " ".join(re.findall(r"[a-z0-9]+", unicodedata.normalize("NFKC", value).casefold()))


def _score(row: dict[str, Any], query: str, project: str | None) -> tuple[int, list[str]]:
    q = _normalize(query)
    tokens = set(q.split())
    score = 0
    trace: list[str] = []
    fields = [(row["id"], 100), *[(value, 80) for value in row["triggers"]], *[(value, 70) for value in row["aliases"]], (row["title"], 40), (row["summary"], 20)]
    for value, weight in fields:
        normalized = _normalize(value)
        if q == normalized:
            score += weight * 4
            trace.append(f"exact:{weight}:{value}")
        elif q in normalized or normalized in q:
            score += weight * 2
            trace.append(f"phrase:{weight}:{value}")
        else:
            overlap = len(tokens & set(normalized.split()))
            if overlap:
                score += weight * overlap
                trace.append(f"tokens:{weight}x{overlap}:{value}")
    if project and row["domain"] == project:
        score += 15
        trace.append("project-domain:+15")
    return score, trace


def _dependency_order(
    selected: Iterable[str],
    by_id: dict[str, dict[str, Any]],
    *,
    include_evidence: bool = False,
) -> list[tuple[str, str, list[str]]]:
    primary = list(sorted(selected))
    included: set[str] = set(primary)
    reasons: dict[str, set[str]] = {
        topic_id: {"request:primary"} for topic_id in primary
    }
    fields = (
        ("requires_procedures", "prerequisite"),
        ("governed_by", "governing"),
        ("uses_knowledge", "knowledge"),
        *((("supported_by", "evidence"),) if include_evidence else ()),
    )

    def collect(topic_id: str) -> None:
        for field, relation in fields:
            for target in sorted(by_id[topic_id][field]):
                first = target not in included
                included.add(target)
                reasons.setdefault(target, set()).add(f"{topic_id}:{field}")
                if first:
                    collect(target)

    for topic_id in primary:
        collect(topic_id)
    ordered_ids: list[str] = []
    emitted: set[str] = set()

    def emit_procedure(topic_id: str) -> None:
        if topic_id in emitted:
            return
        for dependency in sorted(by_id[topic_id]["requires_procedures"]):
            if dependency in included:
                emit_procedure(dependency)
        if topic_id not in primary:
            emitted.add(topic_id)
            ordered_ids.append(topic_id)

    for topic_id in sorted(included):
        if by_id[topic_id]["artifact_role"] == "procedure":
            emit_procedure(topic_id)
    for topic_id in primary:
        if topic_id not in emitted:
            emitted.add(topic_id)
            ordered_ids.append(topic_id)
    for role in ("guideline", "knowledge", "evidence"):
        for topic_id in sorted(included):
            if topic_id not in emitted and by_id[topic_id]["artifact_role"] == role:
                emitted.add(topic_id)
                ordered_ids.append(topic_id)
    relation_for_role = {
        "procedure": "prerequisite",
        "guideline": "governing",
        "knowledge": "knowledge",
        "evidence": "evidence",
    }
    return [
        (
            topic_id,
            "primary" if topic_id in primary
            else relation_for_role[by_id[topic_id]["artifact_role"]],
            sorted(reasons[topic_id]),
        )
        for topic_id in ordered_ids
    ]


def _plan_hash(plan: dict[str, Any]) -> str:
    return hashlib.sha256(_json_bytes({key: value for key, value in plan.items() if key != "plan_sha256"})).hexdigest()


def resolve_library(
    vault: Path,
    *,
    query: str | None = None,
    route: str | None = None,
    role: str = "auto",
    project: str | None = None,
    intent: str | None = None,
    include_evidence: bool = False,
    max_bytes: int | None = None,
    max_domains: int | None = None,
    max_topics: int | None = None,
) -> dict[str, Any]:
    if bool(query) == bool(route):
        raise LibraryError("resolve-library requires exactly one of query or route")
    if role not in ROLES:
        raise LibraryError(f"invalid role: {role}")
    if intent is not None and intent not in INTENTS:
        raise LibraryError(f"invalid intent: {intent}")
    root, catalog, manifest = _load_generated(vault)
    routines_inventory = json.loads((root / ".kosmic/routines.json").read_text(encoding="utf-8"))
    audience_eligible = [
        row for row in catalog["topics"]
        if row["status"] == "stable"
        and (role == "auto" or row["audience"] == role)
    ]
    intent_origin = "explicit" if intent is not None else "inferred"
    inferred = intent
    if inferred is None and query:
        tokens = set(_normalize(query).split())
        signals = {
            "do": {
                "add", "build", "create", "debug", "fix", "generate",
                "implement", "install", "migrate", "run", "update",
            },
            "investigate": {"why", "investigate", "failure", "failed"},
            "understand": {"understand", "explain", "what"},
            "check": {"check", "review", "verify"},
        }
        matched = [
            candidate for candidate, words in signals.items() if tokens & words
        ]
        if len(matched) > 1:
            raise LibraryError("AMBIGUOUS_INTENT: " + ", ".join(sorted(matched)))
        inferred = matched[0] if matched else "understand"
    roles_for_intent = {
        "do": ("procedure",),
        "check": ("guideline", "procedure"),
        "understand": ("knowledge", "guideline"),
        "investigate": ("evidence", "knowledge"),
    }
    traces: list[str] = []
    selected_domain_ids: list[str] = []
    if route:
        matches = [row for row in audience_eligible if row["id"] == route]
        if matches:
            selected_row = matches[0]
            inferred = inferred or {
                "procedure": "do",
                "guideline": "check",
                "knowledge": "understand",
                "evidence": "investigate",
            }[selected_row["artifact_role"]]
            if selected_row["artifact_role"] not in roles_for_intent[inferred]:
                raise LibraryError(
                    f"NO_EXECUTABLE_MATCH: route {route} is not valid "
                    f"for intent {inferred}"
                )
            selected = [selected_row["id"]]
            traces.append(f"exact-route:{route}")
        elif route in {row["id"] for row in catalog["domains"]}:
            selected = []
            selected_domain_ids = [route]
            inferred = inferred or "understand"
            traces.append(f"exact-domain-route:{route}")
        else:
            raise LibraryError(f"NO_MATCH: {route}")
    else:
        assert inferred is not None
        allowed_roles = roles_for_intent[inferred]
        scored: list[tuple[int, dict[str, Any], list[str]]] = []
        for candidate_role in allowed_roles:
            eligible = [
                row for row in audience_eligible
                if row["artifact_role"] == candidate_role
            ]
            if candidate_role == "evidence":
                superseded = {
                    target for row in eligible for target in row["supersedes"]
                }
                eligible = [
                    row for row in eligible if row["id"] not in superseded
                ]
            scored = [
                (score, row, trace)
                for row in eligible
                for score, trace in [_score(row, query or "", project)]
                if score > 0
            ]
            if scored:
                break
        if not scored:
            raise LibraryError(
                ("NO_EXECUTABLE_MATCH" if inferred == "do" else "NO_MATCH")
                + f": no eligible {' or '.join(allowed_roles)} topic"
            )
        best = max(score for score, _, _ in scored)
        winners = sorted(
            (row for score, row, _ in scored if score == best),
            key=lambda row: row["id"],
        )
        if len(winners) != 1:
            raise LibraryError(
                "AMBIGUOUS: " + ", ".join(row["id"] for row in winners[:5])
            )
        selected = [winners[0]["id"]]
        traces.extend(
            f"{winners[0]['id']}:{item}"
            for score, row, trace in scored
            if row["id"] == winners[0]["id"]
            for item in trace
        )
    by_id = {row["id"]: row for row in catalog["topics"]}
    ordered_pairs = _dependency_order(
        selected,
        by_id,
        include_evidence=include_evidence or inferred == "investigate",
    )
    ordered = [
        dict(by_id[topic_id], relation=relation, included_by=included_by)
        for topic_id, relation, included_by in ordered_pairs
    ]
    domains_by_id = {row["id"]: row for row in catalog["domains"]}
    domain_ids = sorted({*selected_domain_ids, *(row["domain"] for row in ordered)})
    domains = [domains_by_id[domain] for domain in domain_ids]
    policy = manifest["policy"]
    byte_limit = min(int(max_bytes or policy["max_packet_bytes"]), int(policy["max_packet_bytes"]))
    domain_limit = min(int(max_domains or policy["max_domains"]), int(policy["max_domains"]))
    topic_limit = min(int(max_topics or policy["max_topics"]), int(policy["max_topics"]))
    routine_ids = sorted({routine_id for row in ordered for routine_id in row.get("uses_routines", [])})
    routines_by_id = {row["id"]: row for row in routines_inventory["routines"]}
    routines = [routines_by_id[routine_id] for routine_id in routine_ids]
    chunks = [
        *(_packet_chunk("domain", row, (root / row["path"]).read_text(encoding="utf-8")) for row in domains),
        *(_packet_chunk("routine", row, json.dumps(row, ensure_ascii=False, sort_keys=True, separators=(",", ":"))) for row in routines),
        *(_packet_chunk("topic", row, (root / row["path"]).read_text(encoding="utf-8")) for row in ordered),
    ]
    total = len("\n".join(chunks).encode("utf-8"))
    if total > byte_limit or len(domains) > domain_limit or len(ordered) > topic_limit:
        raise LibraryError(
            f"BUDGET_EXCEEDED: bytes {total}/{byte_limit}, "
            f"domains {len(domains)}/{domain_limit}, topics {len(ordered)}/{topic_limit}"
        )
    included_ids = {item["id"] for item in ordered}
    plan: dict[str, Any] = {
        "schema": SCHEMA_VERSION,
        "intent": inferred,
        "intent_origin": intent_origin,
        "mode": "task" if inferred == "do" else "reference",
        "primary_topic": selected[0] if selected else "",
        "request": {
            "query": query or "", "route": route or "", "role": role,
            "intent": inferred, "intent_origin": intent_origin,
            "include_evidence": include_evidence, "project": project or "",
            "max_bytes": byte_limit, "max_domains": domain_limit,
            "max_topics": topic_limit,
        },
        "manifest_sha256": _sha(root / ".kosmic/manifest.json"),
        "routine_inventory_sha256": manifest["routine_inventory_sha256"],
        "domains": [{key: row[key] for key in ("id", "path", "sha256", "context_bytes")} for row in domains],
        "topics": [{key: row[key] for key in ("id", "path", "sha256", "context_bytes", "artifact_role", "relation", "included_by")} for row in ordered],
        "routines": [{key: row[key] for key in ("id", "module", "symbol", "summary", "side_effects", "source_sha256", "declaration_sha256", "routine_sha256")} for row in routines],
        "ordered_loads": [*(f"domain:{row['id']}" for row in domains), *(f"routine:{row['id']}" for row in routines), *(f"topic:{row['id']}" for row in ordered)],
        "total_bytes": total,
        "trace": traces,
        "exclusions": [
            {
                "id": row["id"],
                "reason": (
                    f"status:{row['status']}"
                    if row["status"] != "stable"
                    else f"audience:{row['audience']}"
                    if role != "auto" and row["audience"] != role
                    else f"artifact_role:{row['artifact_role']}"
                ),
            }
            for row in catalog["topics"]
            if row["id"] not in included_ids
        ],
    }
    plan["plan_sha256"] = _plan_hash(plan)
    return plan



def _packet_chunk(kind: str, row: dict[str, Any], content: str) -> str:
    semantic = (
        f" role:{row['artifact_role']} relation:{row['relation']}"
        f" included_by:{','.join(row.get('included_by', [row['relation']]))}"
        if kind == "topic" and "artifact_role" in row else ""
    )
    digest = row.get("sha256") or row.get("routine_sha256")
    return f"<!-- {kind}:{row['id']}{semantic} sha256:{digest} -->\n{content.rstrip()}\n"


def load_recipe_packet(vault: Path, plan: dict[str, Any]) -> str:
    root, _, _ = _load_generated(vault)
    if plan.get("schema") != SCHEMA_VERSION or plan.get("plan_sha256") != _plan_hash(plan):
        raise LibraryError("INVALID_PLAN: plan hash mismatch")
    if plan.get("manifest_sha256") != _sha(root / ".kosmic/manifest.json"):
        raise LibraryError("INVALID_PLAN: stale library manifest hash")
    routines_path = root / ".kosmic/routines.json"
    if plan.get("routine_inventory_sha256") != _sha(routines_path):
        raise LibraryError("INVALID_PLAN: stale routine inventory hash")
    inventory_rows = {
        row["id"]: row
        for row in json.loads(routines_path.read_text(encoding="utf-8"))["routines"]
    }
    chunks: list[str] = []
    for row in plan.get("domains", []):
        path = _contained(root, root / str(row["path"]))
        if not path.is_file() or _sha(path) != row["sha256"]:
            raise LibraryError(f"INVALID_PLAN: stale source hash for {row.get('id')}")
        content = path.read_text(encoding="utf-8")
        if len(content.encode("utf-8")) != row["context_bytes"]:
            raise LibraryError(f"INVALID_PLAN: byte cost mismatch for {row.get('id')}")
        chunks.append(_packet_chunk("domain", row, content))
    for row in plan.get("routines", []):
        current = inventory_rows.get(row.get("id"))
        if current is None or any(current.get(key) != value for key, value in row.items()):
            raise LibraryError(f"INVALID_PLAN: stale routine hash for {row.get('id')}")
        chunks.append(_packet_chunk("routine", row, json.dumps(current, ensure_ascii=False, sort_keys=True, separators=(",", ":"))))
    for row in plan.get("topics", []):
        path = _contained(root, root / str(row["path"]))
        if not path.is_file() or _sha(path) != row["sha256"]:
            raise LibraryError(f"INVALID_PLAN: stale source hash for {row.get('id')}")
        content = path.read_text(encoding="utf-8")
        if len(content.encode("utf-8")) != row["context_bytes"]:
            raise LibraryError(f"INVALID_PLAN: byte cost mismatch for {row.get('id')}")
        chunks.append(_packet_chunk("topic", row, content))
    packet = "\n".join(chunks)
    if len(packet.encode("utf-8")) != plan.get("total_bytes"):
        raise LibraryError("INVALID_PLAN: total byte cost mismatch")
    return packet


def _migrate_classified_topics(vault: Path, project: Path, assignments: dict[str, Any], *,
                              work_record: str | None = None) -> dict[str, Any]:
    """Recover existing legacy Topic metadata from explicit typed assignments."""
    _authorize_library_mutation(vault, work_record, "migrate-library")
    root = _library_root(vault)
    project = project.expanduser().resolve()
    project_id = str(parse_document(project / "ProjectEntry.md").metadata.get("project_id") or "")
    if not assignments:
        raise LibraryError("semantic role classification must name existing topics")
    staging = Path(tempfile.mkdtemp(prefix="kosmic-role-migration-", dir=root.parent))
    staged_root = staging / "Skills"
    migrations: list[dict[str, Any]] = []
    try:
        shutil.copytree(root, staged_root, symlinks=True)
        for key, assignment in sorted(assignments.items()):
            if not isinstance(assignment, dict):
                raise LibraryError(f"invalid semantic role classification for {key}")
            required = {"source", "target_id", "artifact_role", *RELATION_ROLES}
            if required - set(assignment):
                raise LibraryError(f"semantic role classification for {key} lacks typed fields")
            target_id = assignment["target_id"]
            if not isinstance(target_id, str) or not ID_RE.fullmatch(target_id) \
                    or target_id.count("/") != 2 or key != target_id + ".md" \
                    or assignment["source"] != key:
                raise LibraryError(f"semantic role classification changes topic identity: {key}")
            candidate = root
            for part in Path(key).parts:
                candidate = candidate / part
                if candidate.is_symlink():
                    raise LibraryError(f"semantic role classification source is a symlink: {key}")
            source = _contained(root, root / key)
            if not source.is_file():
                raise LibraryError(f"semantic role classification source is missing: {key}")
            raw = source.read_bytes()
            document = parse_document_text(raw.decode("utf-8"), source)
            expected_provenance = assignment.get("source_project", project_id)
            if not isinstance(expected_provenance, str) or not expected_provenance \
                    or document.metadata.get("id") != target_id \
                    or document.metadata.get("source_project") != expected_provenance:
                raise LibraryError(f"semantic role classification source ownership mismatch: {key}")
            role = assignment["artifact_role"]
            if not isinstance(role, str) or role not in ARTIFACT_ROLES:
                raise LibraryError(f"invalid semantic artifact role for {key}")
            relationships = {
                field: _string_list(assignment[field], field, source)
                for field in RELATION_ROLES
            }
            current_type = document.metadata.get("type")
            if current_type == "Domain Topic":
                if document.metadata.get("artifact_role") != role \
                        or any(_string_list(document.metadata.get(field, []), field, source) != values
                               for field, values in relationships.items()):
                    raise LibraryError(f"semantic role classification conflicts with typed topic: {key}")
                continue
            if current_type != "Skill Topic":
                raise LibraryError(f"semantic role classification requires a legacy Skill Topic: {key}")
            if document.metadata.get("artifact_role") not in (None, "", role):
                raise LibraryError(f"semantic role classification conflicts with existing role: {key}")
            if _string_list(document.metadata.get("requires", []), "requires", source):
                raise LibraryError(f"semantic role classification has unclassified legacy dependencies: {key}")
            metadata = dict(document.metadata)
            metadata["type"] = "Domain Topic"
            metadata["artifact_role"] = role
            metadata.pop("requires", None)
            metadata.update(relationships)
            for field in ("outcome", "observed_on"):
                if field in assignment:
                    metadata[field] = assignment[field]
            body = document.body.encode("utf-8")
            header = "---\n" + "".join(
                line for name, value in metadata.items() for line in render_entry(name, value)
            ) + "---\n"
            (staged_root / key).write_bytes(header.encode("utf-8") + body)
            migrations.append({"source": key, "target": target_id, "artifact_role": role,
                               "body_sha256": hashlib.sha256(body).hexdigest()})
        payloads = _generated_payloads(staging, evidence_vault=vault)
        for relative, content in payloads.items():
            destination = staged_root / relative
            candidate = staged_root
            for part in Path(relative).parts:
                candidate = candidate / part
                if candidate.is_symlink():
                    raise LibraryError(f"generated library output is a symlink: {relative}")
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content)
        publish_tree(staged_root, root)
        return {"schema": SCHEMA_VERSION, "project": project_id, "migrations": migrations}
    finally:
        shutil.rmtree(staging, ignore_errors=True)


def migrate_assignments(vault: Path, project: Path, assignments: dict[str, Any], *,
                        work_record: str | None = None) -> dict[str, Any]:
    _authorize_library_mutation(vault, work_record, "migrate-library")
    root = _library_root(vault)
    project = project.expanduser().resolve()
    references = sorted(path for path in (project / "skills").glob("*/references/**/*.md") if path.is_file())
    keys = [path.relative_to(project / "skills").as_posix() for path in references]
    missing = sorted(set(keys) - set(assignments))
    extra = sorted(set(assignments) - set(keys))
    if missing or extra:
        raise LibraryError(f"migration assignments unassigned={missing} unknown={extra}")
    staging = Path(tempfile.mkdtemp(prefix="kosmic-migration-", dir=root.parent))
    shutil.copytree(root, staging / "Skills", dirs_exist_ok=True)
    staged_root = staging / "Skills"
    migrations: list[dict[str, Any]] = []
    try:
        for source, key in zip(references, keys):
            assignment = assignments[key]
            if not isinstance(assignment, dict):
                raise LibraryError(f"migration assignment for {key} must declare target_id, artifact_role, and all typed relationships")
            required_assignment = {"target_id", "artifact_role", *RELATION_ROLES}
            missing_fields = sorted(required_assignment - set(assignment))
            if missing_fields:
                raise LibraryError(f"migration assignment for {key} missing {missing_fields}")
            target_id = str(assignment["target_id"])
            artifact_role = str(assignment["artifact_role"])
            if artifact_role not in ARTIFACT_ROLES:
                raise LibraryError(f"invalid migration artifact_role for {key}: {artifact_role}")
            if not ID_RE.fullmatch(target_id) or target_id.count("/") != 2:
                raise LibraryError(f"invalid migration target: {target_id}")
            domain, audience, slug = target_id.split("/")
            if not (staged_root / domain / "SKILL.md").is_file():
                raise LibraryError(f"migration target domain does not exist: {domain}")
            document = parse_document(source)
            source_audience = str(document.metadata.get("audience") or "")
            if source_audience not in {audience, "both"}:
                raise LibraryError(f"{source}: audience {source_audience!r} does not permit target audience {audience!r}")
            target = staged_root / domain / audience / f"{slug}.md"
            if target.exists():
                raise LibraryError(f"migration collision: {target_id}")
            source_hash = str(document.metadata.get("source_sha256") or "")
            if not SHA256_RE.fullmatch(source_hash):
                raise LibraryError(f"{source}: missing or invalid source_sha256")
            source_reference = str(document.metadata.get("source") or "")
            authoritative = (project / source_reference).resolve()
            try:
                authoritative.relative_to(project)
            except ValueError as error:
                raise LibraryError(f"{source}: source path escapes Project") from error
            if not authoritative.is_file() or _sha(authoritative) != source_hash:
                raise LibraryError(f"{source}: stale or missing authoritative source {source_reference}")
            authoritative_document = parse_document(authoritative)
            evidence = _string_list(authoritative_document.metadata.get("evidence", []), "evidence", authoritative)
            relationships = {field: _string_list(assignment[field], field, source) for field in RELATION_ROLES}
            outcome = str(assignment.get("outcome") or "")
            observed_on = str(assignment.get("observed_on") or "")
            summary = next((line[2:].strip() for line in document.body.splitlines() if line.startswith("# ")), slug)
            metadata = ["---", "type: Domain Topic", f"id: {target_id}", f"domain: {domain}",
                        f"audience: {audience}", f"artifact_role: {artifact_role}", "status: stable",
                        f"summary: {summary}", f"triggers: [{summary}]", f"outcome: {outcome}",
                        "aliases: []", *(f"{field}: [{', '.join(relationships[field])}]" for field in RELATION_ROLES),
                        f"observed_on: {observed_on}", f"evidence: [{', '.join(evidence)}]",
                        f"source_project: {project.name}", f"source_sha256: {source_hash}", "---", ""]
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text("\n".join(metadata) + document.body, encoding="utf-8")
            migrations.append({"source": key, "target": target_id, "source_sha256": source_hash, "evidence": evidence})
        payloads = _generated_payloads(staging, evidence_vault=vault)
        for relative, content in payloads.items():
            path = staged_root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        if any((staged_root / relative).read_bytes() != content for relative, content in payloads.items()):
            raise LibraryError("migration staged generated-byte verification failed")
        backup = root.parent / f".Skills-backup-{os.getpid()}"
        os.replace(root, backup)
        try:
            os.replace(staged_root, root)
        except Exception:
            os.replace(backup, root)
            raise
        shutil.rmtree(backup, ignore_errors=True)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return {"schema": SCHEMA_VERSION, "project": project.name, "migrations": migrations}


def _router_payload(vault: Path) -> dict[str, bytes]:
    root = _library_root(vault)
    manifest_path = root / ".kosmic/manifest.json"
    manifest_hash = _sha(manifest_path)
    policy = json.loads(manifest_path.read_text(encoding="utf-8"))["policy"]
    cli = Path(__file__).resolve().with_name("kosmic_project_skills.py")
    command = f'python3 "{cli}"'
    router = (
        "---\n"
        "name: memnotes-skills\n"
        "description: Resolve and load bounded role-aware packets from the Memnotes Shared Skill Library.\n"
        "---\n\n"
        "# Memnotes Shared Skills\n\n"
        "Use this router for maintained procedures, governing guidelines, reference knowledge, and dated evidence. Do not scan the vault or load every domain.\n\n"
        f"1. Run `{command} resolve-library --vault \"{vault.expanduser().resolve()}\"` with exactly one query or route, the audience role, and optional `--intent do|check|understand|investigate`.\n"
        "2. Inspect the inferred intent, primary topic, typed closure, exclusions, and exact byte cost; save the unchanged JSON plan.\n"
        f"3. Run `{command} load-library --vault \"{vault.expanduser().resolve()}\" --plan PLAN.json`.\n"
        "4. Execute only a `procedure` selected for `do`; treat guidelines as constraints, knowledge as reference, and evidence as historical support.\n\n"
        f"Library budget policy: {policy['max_packet_bytes']} packet bytes, {policy['max_domains']} domains, {policy['max_topics']} topics; requests are clamped to these maxima.\n"
        f"Authoritative library: `{root}`\n"
        f"Manifest SHA-256 at publication: `{manifest_hash}`\n"
        "Failure is closed: stale hashes, ambiguity, missing dependencies, cycles, and budget overflow return no recipe bodies.\n"
    ).encode("utf-8")
    identity = _json_bytes(
        {
            "schema": SCHEMA_VERSION,
            "library_id": "memnotes-skills",
            "manifest_sha256": manifest_hash,
            "vault": str(vault.expanduser().resolve()),
        }
    )
    return {"SKILL.md": router, ".kosmic-library-router.json": identity}


def _canonical_router(vault: Path) -> Path:
    return _library_root(vault) / ".kosmic/router"


def generate_router(vault: Path) -> Path:
    validate_library(vault)
    destination = _canonical_router(vault)
    staging = Path(tempfile.mkdtemp(prefix="kosmic-router-stage-", dir=destination.parent))
    try:
        for relative, content in _router_payload(vault).items():
            path = staging / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        backup = destination.parent / f".router-backup-{os.getpid()}"
        if destination.exists():
            os.replace(destination, backup)
        try:
            os.replace(staging, destination)
        except Exception:
            if backup.exists():
                os.replace(backup, destination)
            raise
        shutil.rmtree(backup, ignore_errors=True)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return destination


def _router_matches(vault: Path, path: Path) -> bool:
    if not path.is_dir():
        return False
    expected = _router_payload(vault)
    return all((path / relative).is_file() and (path / relative).read_bytes() == content for relative, content in expected.items())


def install_shared_router(vault: Path, destination_root: Path, *,
                          work_record: str | None = None) -> Path:
    _authorize_library_mutation(vault, work_record, "install-library")
    source = generate_router(vault)
    destination_root = destination_root.expanduser().resolve()
    destination_root.mkdir(parents=True, exist_ok=True)
    destination = destination_root / "memnotes-skills"
    identity = destination / ".kosmic-library-router.json"
    if destination.exists() and not identity.is_file():
        raise LibraryError(f"INSTALLATION_COLLISION: installation collision at unmanaged path: {destination}")
    managed_pairs = sorted(path for path in destination_root.iterdir()
                           if path.is_dir() and (path / ".kosmic-projection.json").is_file())
    staging = Path(tempfile.mkdtemp(prefix=".memnotes-skills-stage-", dir=destination_root))
    shutil.copytree(source, staging, dirs_exist_ok=True)
    backup = Path(tempfile.mkdtemp(prefix=".memnotes-skills-backup-", dir=destination_root))
    moved: list[tuple[Path, Path]] = []
    installed = False
    rollback_complete = True
    try:
        for old in [destination, *managed_pairs]:
            if old.exists():
                saved = backup / old.name
                os.replace(old, saved)
                moved.append((saved, old))
        os.replace(staging, destination)
        installed = True
        if not _router_matches(vault, destination):
            raise LibraryError("installed Shared Skill Router failed byte verification")
    except Exception:
        if installed:
            shutil.rmtree(destination, ignore_errors=True)
        for saved, old in reversed(moved):
            if saved.exists():
                try:
                    os.replace(saved, old)
                except OSError:
                    rollback_complete = False
                    raise
        raise
    finally:
        shutil.rmtree(staging, ignore_errors=True)
        if rollback_complete:
            shutil.rmtree(backup, ignore_errors=True)
    return destination


def check_shared_router_installation(vault: Path, destination_root: Path) -> Path:
    destination = destination_root.expanduser().resolve() / "memnotes-skills"
    if not _router_matches(vault, destination):
        raise LibraryError(f"Shared Skill Router is missing or stale: {destination}")
    stale_pairs = [
        path.name for path in destination.parent.iterdir()
        if path.is_dir() and (path / ".kosmic-projection.json").is_file()
    ]
    if stale_pairs:
        raise LibraryError("managed Project Skill Pairs remain installed: " + ", ".join(sorted(stale_pairs)))
    return destination
