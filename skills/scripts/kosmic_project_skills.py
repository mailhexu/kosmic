def collect_provenance(repo: Path) -> tuple[str, str]:
    """Return (git_head, worktree_tree) for the exact current code state.

    Uses a temporary index so the real index and working tree are untouched;
    the worktree tree covers tracked and untracked (non-ignored) files.
    """
    import subprocess

    def git(*args: str, env: dict[str, str] | None = None) -> str:
        proc = subprocess.run(
            ["git", "-C", str(repo), *args], capture_output=True, text=True, env=env
        )
        if proc.returncode != 0:
            raise KosmicError(
                f"provenance: git {' '.join(args)} failed: {proc.stderr.strip()}",
                exit_code=4,
            )
        return proc.stdout.strip()

    head = git("rev-parse", "HEAD")
    head_tree = git("rev-parse", "HEAD^{tree}")
    with ephemeral_command_run(repo, purpose="provenance") as scratch:
        env = {**os.environ, "GIT_INDEX_FILE": str(scratch / "index")}
        git("add", "-A", "--", env=env)
        worktree_tree = git("write-tree", env=env)
    return head, "clean" if worktree_tree == head_tree else worktree_tree


def install_pointer(project: Project, instructions: Path, *,
                    work_record: str | None = None) -> Path:
    # AD-SW8-R2: source authority is the canonical pair; the instructions
    # file is a command-declared derived target of the same triggering
    # record, authorized before any write.
    resolved_instructions = instructions.expanduser().resolve()
    record = require_work_record(project.root, [project.canonical_root],
                                 work_record=work_record, purpose="install")
    validate_current_projection(project, project.canonical_root)
    instructions = resolved_instructions
    start = f"<!-- KOSMIC-SKILLS:{project.project_id}:START -->"
    end = f"<!-- KOSMIC-SKILLS:{project.project_id}:END -->"
    section = "\n".join(
        [
            start,
            f"## {project.project_id} Project Skills",
            "",
            f"- Usage Skill: `{project.canonical_root / project.usage_name}`",
            f"- Development Skill: `{project.canonical_root / project.development_name}`",
            f"- Contributor work must consult Development, which requires `{project.usage_name}` for consumer and shared guidance.",
            *record_first_contract(project),
            end,
        ]
    )
    current = instructions.read_text(encoding="utf-8") if instructions.exists() else ""
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.DOTALL)
    if pattern.search(current):
        updated = pattern.sub(section, current)
    else:
        separator = "\n\n" if current.strip() else ""
        updated = current.rstrip() + separator + section + "\n"
    atomic_write(instructions, updated)
    return instructions


def as_string_list(value: Any) -> list[str]:
    if value is None or value == "":
        return []
    if isinstance(value, list):
        return [str(item) for item in value]
    return [str(value)]


def resolve_related_note(project: Project, reference: str) -> Path:
    cleaned = reference.strip()
    markdown_link = re.fullmatch(r"\[[^\]]+\]\(([^)]+)\)", cleaned)
    if markdown_link:
        cleaned = unquote(markdown_link.group(1)).split("#", 1)[0]
    else:
        cleaned = cleaned.removeprefix("[[").removesuffix("]]").split("|", 1)[0]
    candidate = Path(cleaned)
    if candidate.suffix != ".md":
        candidate = candidate.with_suffix(".md")
    if candidate.parts and candidate.parts[0] == "notes":
        path = project.root / candidate
    else:
        path = project.notes_dir / candidate
    resolved = path.resolve()
    try:
        resolved.relative_to(project.notes_dir.resolve())
    except ValueError as error:
        raise KosmicError(f"related note escapes Project notes: {reference}") from error
    return resolved


def parse_math_protocol(stdout: str, slug: str) -> tuple[str, str, tuple[MathResult, ...]]:
    try:
        payload = json.loads(stdout)
    except (json.JSONDecodeError, UnicodeError) as error:
        raise KosmicError(
            f"check-math {slug} protocol: stdout is not exactly one JSON object; "
            "remedy: emit only the version-1 JSON payload"
        ) from error
    if not isinstance(payload, dict) or set(payload) != {
        "schema_version",
        "python_version",
        "sympy_version",
        "results",
    }:
        raise KosmicError(
            f"check-math {slug} protocol: invalid top-level schema; "
            "remedy: emit exactly schema_version, python_version, sympy_version, results"
        )
    if type(payload["schema_version"]) is not int or payload["schema_version"] != 1:
        raise KosmicError(
            f"check-math {slug} protocol: unsupported schema_version; "
            "remedy: emit schema_version 1"
        )
    python_version = payload["python_version"]
    sympy_version = payload["sympy_version"]
    if (
        not isinstance(python_version, str)
        or not VERSION_RE.fullmatch(python_version)
        or not isinstance(sympy_version, str)
        or not VERSION_RE.fullmatch(sympy_version)
    ):
        raise KosmicError(
            f"check-math {slug} protocol: invalid Python/SymPy versions; "
            "remedy: emit dotted version strings"
        )
    raw_results = payload["results"]
    if not isinstance(raw_results, list) or not raw_results:
        raise KosmicError(
            f"check-math {slug} protocol: results must be non-empty; "
            "remedy: emit at least one named result"
        )
    results: list[MathResult] = []
    for raw_result in raw_results:
        if not isinstance(raw_result, dict) or set(raw_result) != {
            "name",
            "srepr",
            "latex",
        }:
            raise KosmicError(
                f"check-math {slug} protocol: invalid result schema; "
                "remedy: emit exactly name, srepr, and latex"
            )
        name = raw_result["name"]
        srepr = raw_result["srepr"]
        latex = raw_result["latex"]
        if not isinstance(name, str) or not MATH_RESULT_NAME_RE.fullmatch(name):
            raise KosmicError(
                f"check-math {slug} protocol: invalid result name; "
                "remedy: use [a-z][a-z0-9_]*"
            )
        if not isinstance(srepr, str) or not srepr:
            raise KosmicError(
                f"check-math {slug} protocol: empty srepr for {name}; "
                "remedy: emit the canonical SymPy srepr"
            )
        if not isinstance(latex, str) or not latex:
            raise KosmicError(
                f"check-math {slug} protocol: empty latex for {name}; "
                "remedy: emit the rendered LaTeX"
            )
        results.append(
            MathResult(
                name=name,
                srepr=srepr.replace("\r\n", "\n"),
                latex=latex.replace("\r\n", "\n"),
            )
        )
    names = [result.name for result in results]
    if names != sorted(names) or len(names) != len(set(names)):
        raise KosmicError(
            f"check-math {slug} protocol: result names are not sorted and unique; "
            "remedy: sort and deduplicate results by name"
        )
    return python_version, sympy_version, tuple(results)


def execute_math_entry(entry: MathEntry, timeout: float) -> tuple[str, str, tuple[MathResult, ...]]:
    environment = os.environ.copy()
    environment.update(
        {
            "PYTHONHASHSEED": "0",
            "PYTHONIOENCODING": "utf-8",
            "LC_ALL": "C.UTF-8",
            "LANG": "C.UTF-8",
        }
    )
    try:
        process = subprocess.run(
            [sys.executable, entry.script_path.name, "--kosmic-json"],
            cwd=entry.script_path.parent,
            env=environment,
            text=True,
            encoding="utf-8",
            capture_output=True,
            timeout=timeout,
            check=False,
        )
    except subprocess.TimeoutExpired as error:
        raise KosmicError(
            f"check-math {entry.slug} process: timed out after {timeout:g}s; "
            "remedy: optimize the derivation or increase --timeout"
        ) from error
    if process.returncode != 0:
        diagnostic = process.stderr.strip()
        detail = f" ({diagnostic})" if diagnostic else ""
        raise KosmicError(
            f"check-math {entry.slug} process: exited {process.returncode}{detail}; "
            "remedy: run the derivation directly and fix its error"
        )
    return parse_math_protocol(process.stdout, entry.slug)


def selected_math_entries(
    registry: MathRegistry, slugs: Sequence[str]
) -> tuple[MathEntry, ...]:
    selected = sorted(set(slugs)) if slugs else sorted(
        slug for slug, entry in registry.entries.items() if entry.status != "deprecated"
    )
    if not selected:
        raise KosmicError("check-math found no active derivations")
    entries: list[MathEntry] = []
    for slug in selected:
        entry = registry.entries.get(slug)
        if entry is None or entry.status == "deprecated":
            raise KosmicError(
                f"check-math selection: unknown active derivation {slug}; "
                "remedy: choose a slug from mathdocs/index.md"
            )
        entries.append(entry)
    return tuple(entries)


def execute_math_entries(
    entries: Sequence[MathEntry], timeout: float
) -> tuple[
    dict[str, tuple[str, str, tuple[MathResult, ...]]],
    dict[str, str],
]:
    executed: dict[str, tuple[str, str, tuple[MathResult, ...]]] = {}
    failures: dict[str, str] = {}
    for entry in entries:
        try:
            executed[entry.slug] = execute_math_entry(entry, timeout)
        except KosmicError as error:
            failures[entry.slug] = str(error)
    return executed, failures


def report_math_statuses(
    entries: Sequence[MathEntry], failures: dict[str, str]
) -> None:
    for entry in entries:
        if entry.slug in failures:
            print(f"{entry.slug}: FAIL - {failures[entry.slug]}", file=sys.stderr)
        else:
            print(f"{entry.slug}: PASS")
    if failures:
        passed = len(entries) - len(failures)
        raise KosmicError(
            f"check-math summary: {passed} passed, {len(failures)} failed"
        )


def update_math_note(
    text: str,
    project_id: str,
    slug: str,
    results: Sequence[MathResult],
    metadata_updates: dict[str, str],
) -> str:
    lines = text.splitlines(keepends=True)
    delimiters = [index for index, line in enumerate(lines) if line.strip() == "---"]
    if len(delimiters) < 2:
        raise KosmicError(f"mathdocs/{slug}.md is missing frontmatter")
    start, end = delimiters[0], delimiters[1]
    found: set[str] = set()
    for index in range(start + 1, end):
        if ":" not in lines[index]:
            continue
        key = lines[index].split(":", 1)[0].strip()
        if key in metadata_updates:
            newline = "\n" if lines[index].endswith("\n") else ""
            lines[index] = f"{key}: {metadata_updates[key]}{newline}"
            found.add(key)
    missing = [
        f"{key}: {value}\n"
        for key, value in metadata_updates.items()
        if key not in found
    ]
    lines[end:end] = missing
    updated = "".join(lines)

    rendered = render_math_results(project_id, slug, results)
    if MATH_RESULTS_START in updated or MATH_RESULTS_END in updated:
        if updated.count(MATH_RESULTS_START) != 1 or updated.count(MATH_RESULTS_END) != 1:
            raise KosmicError(
                f"Math Derivation {slug} must contain exactly one generated result region"
            )
        region_start = updated.index(MATH_RESULTS_START)
        region_end = updated.index(MATH_RESULTS_END, region_start) + len(MATH_RESULTS_END)
        return updated[:region_start] + rendered + updated[region_end:]

    insertion = f"\n{rendered}\n"
    corrections = updated.find("\n## Corrections")
    if corrections >= 0:
        return updated[:corrections] + insertion + updated[corrections:]
    return updated.rstrip("\n") + insertion


def update_mathdocs(
    project: Project,
    slugs: Sequence[str],
    timeout: float,
    source_root: Path,
) -> tuple[str, ...]:
    selected = slugs if slugs else None
    registry = load_math_registry(project, require_current_source=False, only_slugs=selected)
    if selected is None:
        validate_notes_bundle(project.notes_dir, registry)
    entries = selected_math_entries(registry, slugs)
    executed, failures = execute_math_entries(entries, timeout)
    report_math_statuses(entries, failures)

    timestamp = (
        datetime.now(timezone.utc)
        .isoformat(timespec="seconds")
        .replace("+00:00", "Z")
    )
    source_directory = str(source_root.expanduser().resolve())
    host = socket.gethostname()
    temporary = Path(
        tempfile.mkdtemp(prefix=".kosmic-mathdocs-", dir=project.root)
    )
    try:
        shutil.copytree(project.mathdocs_dir, temporary, dirs_exist_ok=True)
        for entry in entries:
            python_version, sympy_version, results = executed[entry.slug]
            staged_note = temporary / entry.note_path.name
            staged_script = temporary / entry.script_path.name
            updates = {
                "source_sha256": sha256_bytes(staged_script.read_bytes()),
                "python_version": python_version,
                "sympy_version": sympy_version,
                "verified_at": timestamp,
                "verified_host": host,
                "verified_directory": source_directory,
            }
            atomic_write(
                staged_note,
                update_math_note(
                    staged_note.read_text(encoding="utf-8"),
                    project.project_id,
                    entry.slug,
                    results,
                    updates,
                ),
            )
        load_math_registry(project, temporary, only_slugs=selected)
        publish_tree(temporary, project.mathdocs_dir)
    finally:
        if temporary.exists():
            shutil.rmtree(temporary, ignore_errors=True)
    load_math_registry(project, only_slugs=selected)
    return tuple(entry.slug for entry in entries)


def check_math(
    project: Project,
    slugs: Sequence[str],
    timeout: float,
    *,
    update: bool = False,
    source_root: Path | None = None,
    work_record: str | None = None,
) -> tuple[str, ...]:
    if timeout <= 0:
        raise KosmicError("check-math timeout must be positive")
    if update:
        # AD-SW8: --update rewrites verified Math Derivation notes in place;
        # without --update the command is strictly read-only.
        require_work_record(project.root, [project.mathdocs_dir],
                             work_record=work_record, purpose="check-math --update")
        return update_mathdocs(project, slugs, timeout, source_root or Path.cwd())
    print(
        "warning: executing trusted Project derivation code without an OS sandbox",
        file=sys.stderr,
    )
    registry = (load_math_registry(project, only_slugs=slugs)
                if slugs else validate_project_content(project))
    entries = selected_math_entries(registry, slugs)
    executable: list[MathEntry] = []
    failures: dict[str, str] = {}
    for entry in entries:
        if entry.status != "stable":
            failures[entry.slug] = (
                f"check-math {entry.slug} note: status is {entry.status}; "
                "remedy: verify and promote the Math Derivation note"
            )
        else:
            executable.append(entry)
    executed, process_failures = execute_math_entries(executable, timeout)
    failures.update(process_failures)
    for entry in executable:
        if entry.slug in failures:
            continue
        python_version, sympy_version, results = executed[entry.slug]
        if python_version != entry.python_version:
            failures[entry.slug] = (
                f"check-math {entry.slug} environment: python_version is "
                f"{python_version}, recorded {entry.python_version}; "
                "remedy: run check-math --update"
            )
        elif sympy_version != entry.sympy_version:
            failures[entry.slug] = (
                f"check-math {entry.slug} environment: sympy_version is "
                f"{sympy_version}, recorded {entry.sympy_version}; "
                "remedy: run check-math --update"
            )
        elif results != entry.results:
            failures[entry.slug] = (
                f"check-math {entry.slug} result: execution differs from "
                "verified results; remedy: review the derivation and run "
                "check-math --update"
            )
    report_math_statuses(entries, failures)
    return tuple(entry.slug for entry in entries)


def validate_math_implementation(
    project: Project,
    registry: MathRegistry,
    document: MarkdownDocument,
    source_root: Path,
) -> None:
    has_derivations = "derivations" in document.metadata
    has_files = "math_implementation_files" in document.metadata
    if not has_derivations and not has_files:
        return
    if not has_derivations or not has_files:
        missing = "derivations" if not has_derivations else "math_implementation_files"
        raise KosmicError(
            f"math completion gate requires {missing} when either math field is declared"
        )
    slugs = as_string_list(document.metadata.get("derivations"))
    file_references = as_path_list(document.metadata.get("math_implementation_files"))
    if not slugs or not file_references:
        raise KosmicError(
            "math completion gate requires non-empty derivations and "
            "math_implementation_files"
        )
    if len(slugs) != len(set(slugs)):
        raise KosmicError("math completion gate derivations must be unique")
    for slug in slugs:
        if not MATH_SLUG_RE.fullmatch(slug):
            raise KosmicError(f"invalid derivation slug in work item: {slug}")
        entry = registry.entries.get(slug)
        if entry is None or entry.status != "stable":
            raise KosmicError(
                f"work-item derivation is not stable and current: {slug}"
            )

    root = source_root.expanduser().resolve()
    covered: set[str] = set()
    for reference in file_references:
        relative = Path(reference)
        if relative.is_absolute() or ".." in relative.parts:
            raise KosmicError(
                f"math implementation path must be relative and non-traversing: {reference}"
            )
        candidate = (root / relative).resolve()
        try:
            candidate.relative_to(root)
        except ValueError as error:
            raise KosmicError(
                f"math implementation path escapes source root: {reference}"
            ) from error
        if not candidate.is_file():
            raise KosmicError(
                f"math implementation path is not a file: {reference}"
            )
        try:
            text = candidate.read_text(encoding="utf-8")
        except UnicodeError as error:
            raise KosmicError(
                f"math implementation file is not UTF-8 text: {reference}"
            ) from error
        file_covered: set[str] = set()
        for match in IMPLEMENTATION_MATHDOC_RE.finditer(text):
            project_id, slug, result_name = match.groups()
            if project_id != project.project_id:
                raise KosmicError(
                    f"math implementation reference uses another Project: "
                    f"{project_id}/{slug}"
                )
            if slug not in slugs:
                raise KosmicError(
                    f"math implementation reference is not declared: {slug}"
                )
            if result_name is not None:
                known = {result.name for result in registry.entries[slug].results}
                if result_name not in known:
                    raise KosmicError(
                        f"unknown MathDoc result in implementation: {slug}#{result_name}"
                    )
            file_covered.add(slug)
        if not file_covered:
            raise KosmicError(
                f"math implementation file has no declared MathDoc reference: {reference}"
            )
        covered.update(file_covered)
    missing_coverage = sorted(set(slugs) - covered)
    if missing_coverage:
        raise KosmicError(
            "declared derivations have no implementation reference: "
            + ", ".join(missing_coverage)
        )


def contained_project_path(project: Project, reference: str, field: str) -> Path:
    relative = Path(reference)
    if relative.is_absolute():
        raise KosmicError(f"Skill Proposal {field} must be Project-relative: {reference}")
    resolved = (project.root / relative).resolve()
    try:
        resolved.relative_to(project.root)
    except ValueError as error:
        raise KosmicError(f"Skill Proposal {field} escapes Project: {reference}") from error
    return resolved


def proposal_section(body: str, heading: str) -> str:
    lines = body.splitlines(keepends=True)
    collecting = False
    collected: list[str] = []
    fence: str | None = None
    for line in lines:
        marker = line.lstrip()[:3]
        if marker in {"```", "~~~"}:
            fence = None if fence == marker else marker
        if fence is None and re.fullmatch(r"## .+?\s*\n?", line):
            current = line.strip()[3:]
            if collecting:
                break
            collecting = current == heading
            continue
        if collecting:
            collected.append(line)
    return "".join(collected).strip()


def proposal_fingerprint(
    result: str,
    scope: str,
    target: str,
    artifact_role: str | None,
    related_notes: Sequence[str],
    evidence_packs: Sequence[str],
    body: str,
    routine_fields: dict[str, object] | None = None,
) -> str:
    change = proposal_section(
        body, "No-Action Reason" if result == "no_action" else "Proposed Change"
    )
    payload: dict[str, object] = {
        "result": result,
        "scope": scope,
        "target": target,
        "related_notes": sorted(related_notes),
        "evidence_packs": sorted(evidence_packs),
        "change": change,
    }
    if artifact_role is not None:
        payload["artifact_role"] = artifact_role
    if routine_fields is not None:
        payload.update(routine_fields)
    return sha256_bytes(
        json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    )


def validate_input_manifest(project: Project, references: Sequence[str], *,
                            historical: bool = False) -> dict[str, str]:
    """Validate a Skill Proposal's curated input-manifest snapshot.

    The manifest file and its recorded pins are immutable curated inputs:
    bytes are never repinned or re-blessed. ``historical`` (done/terminal
    proposals) reads entries against evolving canonical surfaces — live
    knowledge notes (``notes/``) and the ``routine://`` registry — as
    recorded facts (path containment still enforced, no live re-hash), so
    later legitimate refinement of a canonical source note never revokes a
    completed proposal. Every other declared source (curated snapshot
    copies, evidence records, subproject specs, other artifacts) is still
    re-hashed against live bytes: capture validity stays verifiable.
    Non-historical proposals keep full live re-hash of all declared
    sources — current binding, no blanket amnesty (Story 005 preservation).
    """
    if not references:
        raise KosmicError("Skill Proposal input_manifest must not be empty")
    entries: dict[str, str] = {}
    for reference in references:
        path = contained_project_path(project, reference, "input_manifest")
        if not path.is_file():
            raise KosmicError(f"Skill Proposal input_manifest is missing: {reference}")
        for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            match = re.fullmatch(r"- (.+): ([0-9a-f]{64})", line)
            if not match:
                raise KosmicError(
                    f"Skill Proposal input_manifest line {number} must be '- path: sha256'"
                )
            source_ref, recorded_hash = match.groups()
            if historical:
                # Done proposals read pins as recorded facts only where the
                # declared source is an evolving canonical surface (live
                # knowledge notes, the routine registry): later legitimate
                # refinement there must not revoke a completed proposal.
                # Everything else — curated snapshot copies, evidence records,
                # subproject specs — is an immutable capture whose bytes must
                # STILL match the pin: capture validity stays verifiable.
                if source_ref.startswith("routine://"):
                    entries[source_ref] = recorded_hash
                    continue
                if source_ref.startswith("notes/"):
                    contained_project_path(project, source_ref, "input_manifest path")
                    entries[source_ref] = recorded_hash
                    continue
            if source_ref.startswith("routine://"):
                routine_id = source_ref.removeprefix("routine://")
                inventory_path = project.root.parent.parent / "Skills" / ".kosmic" / "routines.json"
                if not inventory_path.is_file():
                    raise KosmicError("Skill Proposal routine input requires generated routine inventory")
                rows = {
                    str(row.get("id")): row
                    for row in read_json(inventory_path).get("routines", [])
                }
                if str(rows.get(routine_id, {}).get("routine_sha256") or "") != recorded_hash:
                    raise KosmicError(
                        f"Skill Proposal input_manifest routine missing or stale: {source_ref}"
                    )
            else:
                source = contained_project_path(project, source_ref, "input_manifest path")
                if not source.is_file() or sha256_bytes(source.read_bytes()) != recorded_hash:
                    raise KosmicError(
                        f"Skill Proposal input_manifest source missing or stale: {source_ref}"
                    )
            entries[source_ref] = recorded_hash
    if not entries:
        raise KosmicError("Skill Proposal input_manifest must list at least one input")
    return entries


def load_skill_proposal(project: Project, path: Path) -> SkillProposal:
    path = path.expanduser().resolve()
    try:
        path.relative_to(project.proposals_dir.resolve())
    except ValueError as error:
        raise KosmicError(f"Skill Proposal path is outside specs/skill-proposals: {path}") from error
    if path.parent != project.proposals_dir.resolve() or not PROPOSAL_FILE_RE.fullmatch(path.name):
        raise KosmicError(
            f"Skill Proposal path must be specs/skill-proposals/YYYY-MM-DD-slug.md: {path}"
        )
    if not path.is_file():
        raise KosmicError(f"missing Skill Proposal: {path}")
    document = require_frontmatter(path.read_text(encoding="utf-8"), str(path))
    metadata = document.metadata
    required = (
        "status", "created", "updated", "result", "scope", "target",
        "target_ref", "target_sha256", "proposer_mode", "proposer_ref",
        "proposer_reason", "input_manifest", "related_notes",
        "behavioral_evidence", "decision", "fingerprint", "reconsiders",
    )
    missing = [field for field in required if field not in metadata]
    if missing:
        raise KosmicError(
            f"Skill Proposal {path.name} is missing fields: {', '.join(missing)}"
        )
    result = str(metadata["result"]).strip()
    target = str(metadata["target"]).strip()
    scope = str(metadata["scope"]).strip()
    status = str(metadata["status"]).strip()
    decision = str(metadata["decision"]).strip()
    artifact_role_explicit = "artifact_role" in metadata
    artifact_role = str(metadata.get("artifact_role") or "procedure").strip()
    target_kind_explicit = "target_kind" in metadata
    target_kind = str(metadata.get("target_kind") or "procedure").strip()
    routine_action = str(metadata.get("routine_action") or "").strip()
    routine_id = str(metadata.get("routine_id") or "").strip()
    linked_proposals = as_string_list(metadata.get("linked_proposals"))
    consumer_approvals = as_string_list(metadata.get("consumer_approvals"))
    if target_kind not in {"procedure", "routine"}:
        raise KosmicError("Skill Proposal target_kind must be procedure or routine")
    if target_kind == "routine":
        expected_results = {
            "create": "create", "extend": "update", "reuse": "no_action",
            "keep_as_prose": "no_action", "none": "no_action",
        }
        if routine_action not in expected_results or result != expected_results[routine_action]:
            raise KosmicError("routine_action is incompatible with Skill Proposal result")
        if scope != "shared-routine":
            raise KosmicError("routine Skill Proposal requires scope: shared-routine")
    elif any((routine_action, routine_id, linked_proposals, consumer_approvals)):
        raise KosmicError("procedure Skill Proposal must omit routine fields")
    if artifact_role_explicit and artifact_role not in ARTIFACT_ROLES:
        raise KosmicError(f"invalid Skill Proposal artifact_role: {artifact_role}")
    if result != "no_action" and artifact_role != "procedure":
        raise KosmicError("Task P create/update proposals are eligible only for artifact_role: procedure")
    if result not in PROPOSAL_RESULTS:
        raise KosmicError("Skill Proposal result must be create, update, or no_action")
    if scope not in PROPOSAL_SCOPES:
        raise KosmicError(f"invalid Skill Proposal scope: {scope}")
    if status not in PROPOSAL_STATUSES or decision not in PROPOSAL_DECISIONS:
        raise KosmicError("invalid Skill Proposal status or decision")
    lifecycle_valid = (
        (status == "draft" and decision == "pending")
        or (status == "approved" and decision == "pending")
        or (status == "done" and decision in {"accepted", "rejected"})
    )
    if not lifecycle_valid:
        raise KosmicError(
            "Skill Proposal lifecycle requires draft|approved with pending, "
            "or done with accepted|rejected"
        )
    for field in ("created", "updated"):
        if not ISO_DATE_RE.fullmatch(str(metadata[field])):
            raise KosmicError(f"Skill Proposal {field} must be YYYY-MM-DD")
    if "evidence_packs" in metadata and status != "done":
        raise KosmicError(
            f"unsupported input declaration 'evidence_packs' in Skill Proposal "
            f"{path.name}: evidence packs are retired (Story 005)"
        )
    related_notes = as_string_list(metadata["related_notes"])
    # Historical reader: done proposals keep their recorded pack list for
    # fingerprint verification only; nothing resolves or validates it.
    evidence_packs = as_string_list(metadata.get("evidence_packs"))
    behavioral_evidence = as_string_list(metadata["behavioral_evidence"])
    for reference in related_notes:
        note = contained_project_path(project, reference, "related_notes")
        if not note.is_file() or note.suffix != ".md":
            raise KosmicError(f"Skill Proposal related note is missing: {reference}")
    for reference in behavioral_evidence:
        evidence_path = contained_project_path(project, reference, "behavioral_evidence")
        if not evidence_path.is_file():
            raise KosmicError(f"Skill Proposal behavioral evidence is missing: {reference}")
    input_manifest = as_string_list(metadata["input_manifest"])
    input_entries = validate_input_manifest(
        project, input_manifest, historical=status == "done")
    proposer_mode = str(metadata["proposer_mode"]).strip()
    if scope in {"global-procedure", "shared-procedure", "shared-routine"} and proposer_mode != "subagent":
        raise KosmicError(f"{scope} Skill Proposal requires proposer_mode: subagent")
    if proposer_mode not in {"subagent", "same-agent"}:
        raise KosmicError("Skill Proposal proposer_mode must be subagent or same-agent")
    if not str(metadata["proposer_ref"]).strip():
        raise KosmicError("Skill Proposal proposer_ref must be non-empty")
    if proposer_mode == "same-agent" and not str(metadata["proposer_reason"]).strip():
        raise KosmicError("same-agent Skill Proposal requires proposer_reason")
    target_ref = str(metadata["target_ref"]).strip()
    target_sha256 = str(metadata["target_sha256"]).strip()
    approved_by = str(metadata.get("approved_by") or "").strip()
    target_prefix = "routine://" if scope == "shared-routine" else "library-skill://" if scope == "shared-procedure" else "skill://"
    if scope == "shared-procedure" and result != "no_action":
        parts = target.split("/")
        if len(parts) != 3 or parts[1] not in {"usage", "development"}:
            raise KosmicError("shared-procedure target must be domain/audience/slug")
        domain_skill = project.root.parent.parent / "Skills" / parts[0] / "SKILL.md"
        if not domain_skill.is_file():
            raise KosmicError(f"shared-procedure target domain is missing: {parts[0]}")
        maintainers = as_string_list(
            parse_library_document(domain_skill).metadata.get("maintainers")
        )
        if decision == "accepted" and approved_by not in maintainers:
            raise KosmicError(
                "OWNERSHIP_REQUIRED: accepted shared-procedure Skill Proposal "
                f"approved_by must name a target Domain Maintainer: {', '.join(maintainers)}"
            )
    if scope == "shared-routine":
        if routine_action in {"create", "extend", "reuse"}:
            if target != routine_id or target.count("/") != 1:
                raise KosmicError("shared-routine target and routine_id must match domain/slug")
            if target_ref != f"routine://{target}":
                raise KosmicError("shared-routine target_ref must match routine://domain/slug")
        elif routine_action == "none":
            if routine_id or target or target_ref or target_sha256:
                raise KosmicError("none requires empty routine target fields")
        elif routine_action == "keep_as_prose":
            if routine_id or not target or target.count("/") != 2 or target_ref != f"library-skill://{target}" or target_sha256:
                raise KosmicError("keep_as_prose requires a procedure target and no routine_id")
        inventory_path = project.root.parent.parent / "Skills" / ".kosmic" / "routines.json"
        inventory_rows: dict[str, dict[str, object]] = {}
        if inventory_path.is_file():
            inventory_rows = {
                str(row["id"]): row for row in read_json(inventory_path).get("routines", [])
            }
        if routine_action in {"extend", "reuse"} and status != "done":
            current = inventory_rows.get(routine_id)
            if current is None:
                raise KosmicError(f"routine proposal target is absent from inventory: {routine_id}")
            if target_sha256 != current.get("routine_sha256"):
                raise KosmicError(f"routine proposal target hash is stale: {routine_id}")
        if routine_action == "create" and routine_id in inventory_rows and status != "done":
            raise KosmicError(f"routine create target already exists: {routine_id}")
        if routine_action in {"create", "extend"}:
            candidate = proposal_section(document.body, "Routine Candidate")
            labels = ("Repetition", "Contract", "Expected failures", "Leverage")
            if any(not re.search(rf"(?mi)^{re.escape(label)}:\s*\S", candidate) for label in labels):
                raise KosmicError("Routine Candidate requires Repetition, Contract, Expected failures, and Leverage")
            approval_map: dict[str, str] = {}
            for approval in consumer_approvals:
                domain, separator, maintainer = approval.partition(":")
                if not separator or not domain or not maintainer:
                    raise KosmicError("consumer_approvals entries must be domain:maintainer")
                if domain in approval_map:
                    raise KosmicError(f"duplicate consumer approval domain: {domain}")
                domain_path = project.root.parent.parent / "Skills" / domain / "SKILL.md"
                if not domain_path.is_file():
                    raise KosmicError(f"consumer approval domain is missing: {domain}")
                maintainers = as_string_list(parse_library_document(domain_path).metadata.get("maintainers"))
                if maintainer not in maintainers:
                    raise KosmicError(f"consumer approval is not a Domain Maintainer: {approval}")
                approval_map[domain] = maintainer
            owner_domain = routine_id.split("/", 1)[0]
            required_domains: set[str] = set()
            if routine_action == "extend":
                for procedure_id in inventory_rows[routine_id].get("procedures", []):
                    domain = str(procedure_id).split("/", 1)[0]
                    if domain != owner_domain:
                        required_domains.add(domain)
            current_reference = path.relative_to(project.root).as_posix()
            for linked in linked_proposals:
                linked_path = contained_project_path(project, linked, "linked_proposals")
                if not linked_path.is_file():
                    raise KosmicError(f"linked Skill Proposal is missing: {linked}")
                linked_doc = parse_markdown(linked_path.read_text(encoding="utf-8"))
                if current_reference not in as_string_list(linked_doc.metadata.get("linked_proposals")):
                    raise KosmicError(f"linked Skill Proposal is not reciprocal: {linked}")
                linked_target = str(linked_doc.metadata.get("target") or "")
                linked_domain = linked_target.split("/", 1)[0] if linked_target else ""
                if linked_domain and linked_domain != owner_domain:
                    required_domains.add(linked_domain)
            if set(approval_map) != required_domains:
                raise KosmicError(
                    "consumer_approvals must cover linked consumer domains: "
                    + ", ".join(sorted(required_domains))
                )
        elif consumer_approvals:
            raise KosmicError("reuse, keep_as_prose, and none require empty consumer_approvals")
    if result == "create":
        if not target or target_ref != f"{target_prefix}{target}" or target_sha256 != "empty":
            raise KosmicError(
                "create Skill Proposal requires target, matching target_ref, "
                "and target_sha256: empty"
            )
    elif result == "update":
        if not target or target_ref != f"{target_prefix}{target}" or not SHA256_RE.fullmatch(target_sha256):
            raise KosmicError(
                "update Skill Proposal requires target, matching target_ref, and a SHA-256 pin"
            )
        if target_sha256 not in input_entries.values():
            raise KosmicError(
                "update Skill Proposal target_sha256 is not pinned by input_manifest"
            )
    elif target_kind != "routine" or routine_action == "none":
        if target or target_ref or target_sha256:
            raise KosmicError("no_action Skill Proposal requires empty target fields")
    if scope == "project-knowledge" and result != "no_action":
        raise KosmicError(
            "project-knowledge findings continue through note review and require result: no_action"
        )
    sections = ["Problem", "Evidence", "Applicability", "Behavioral Validation", "Risks"]
    sections.append("No-Action Reason" if result == "no_action" else "Proposed Change")
    empty_sections = [heading for heading in sections if not proposal_section(document.body, heading)]
    if empty_sections:
        raise KosmicError(
            f"Skill Proposal {path.name} has missing or empty sections: {', '.join(empty_sections)}"
        )
    routine_fields = None
    if target_kind_explicit:
        routine_fields = {
            "target_kind": target_kind,
            "routine_action": routine_action,
            "routine_id": routine_id,
            "linked_proposals": sorted(linked_proposals),
            "consumer_approvals": sorted(consumer_approvals),
        }
    computed = proposal_fingerprint(
        result, scope, target, artifact_role if artifact_role_explicit else None,
        related_notes, evidence_packs,
        document.body, routine_fields,
    )
    recorded = str(metadata["fingerprint"]).strip()
    if decision != "pending" and recorded != computed:
        raise KosmicError(f"Skill Proposal fingerprint mismatch; expected {computed}")
    if decision == "accepted" and result != "no_action" and not behavioral_evidence:
        raise KosmicError("accepted create/update Skill Proposal requires behavioral_evidence")
    if result != "no_action":
        validation = proposal_section(document.body, "Behavioral Validation")
        candidate_match = re.search(
            r"(?m)^Candidate paths:\s*\[([^\]]+)\]\s*$", validation
        )
        if not candidate_match:
            raise KosmicError(
                "create/update Skill Proposal Behavioral Validation requires "
                "Candidate paths: [project-relative/path]"
            )
        for raw_candidate in candidate_match.group(1).split(","):
            candidate = contained_project_path(
                project, raw_candidate.strip(), "candidate path"
            )
            try:
                candidate.relative_to(project.canonical_root.resolve())
            except ValueError:
                continue
            raise KosmicError(
                f"Skill Proposal candidate path is canonical: {raw_candidate.strip()}"
            )
    for prior_path in sorted(project.proposals_dir.glob("*.md")):
        if prior_path.resolve() == path:
            continue
        prior = parse_markdown(prior_path.read_text(encoding="utf-8"))
        if str(prior.metadata.get("decision") or "") != "rejected":
            continue
        prior_result = str(prior.metadata.get("result") or "")
        prior_scope = str(prior.metadata.get("scope") or "")
        prior_target = str(prior.metadata.get("target") or "")
        prior_related = as_string_list(prior.metadata.get("related_notes"))
        prior_evidence = as_string_list(prior.metadata.get("evidence_packs"))
        prior_role = str(prior.metadata.get("artifact_role") or "")
        prior_routine_fields = None
        if "target_kind" in prior.metadata:
            prior_routine_fields = {
                "target_kind": str(prior.metadata.get("target_kind") or ""),
                "routine_action": str(prior.metadata.get("routine_action") or ""),
                "routine_id": str(prior.metadata.get("routine_id") or ""),
                "linked_proposals": sorted(as_string_list(prior.metadata.get("linked_proposals"))),
                "consumer_approvals": sorted(as_string_list(prior.metadata.get("consumer_approvals"))),
            }
        prior_fingerprint = proposal_fingerprint(
            prior_result, prior_scope, prior_target, prior_role,
            prior_related, prior_evidence, prior.body, prior_routine_fields,
        )
        if str(prior.metadata.get("fingerprint") or "") != prior_fingerprint:
            raise KosmicError(f"rejected Skill Proposal fingerprint mismatch: {prior_path.name}")
        if prior_fingerprint != computed:
            continue
        reconsiders = str(metadata["reconsiders"]).strip()
        new_evidence = proposal_section(document.body, "New Evidence")
        allowed = False
        if reconsiders:
            reconsidered = contained_project_path(project, reconsiders, "reconsiders")
            allowed = reconsidered == prior_path.resolve() and bool(
                new_evidence and new_evidence.lower() != "none."
            )
        if not allowed:
            raise KosmicError(
                f"equivalent rejected Skill Proposal already exists: {prior_path.name}; "
                "set reconsiders and provide New Evidence"
            )
    return SkillProposal(
        path=path,
        status=status,
        result=result,
        scope=scope,
        artifact_role=artifact_role,
        target=target,
        target_ref=target_ref,
        target_sha256=target_sha256,
        proposer_mode=proposer_mode,
        proposer_ref=str(metadata["proposer_ref"]).strip(),
        input_manifest=tuple(input_manifest),
        related_notes=tuple(related_notes),
        behavioral_evidence=tuple(behavioral_evidence),
        decision=decision,
        fingerprint=computed,
        reconsiders=str(metadata["reconsiders"]).strip(),
        approved_by=approved_by,
    )


