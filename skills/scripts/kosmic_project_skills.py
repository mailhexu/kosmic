def router_text(project: Project, role: str, notes: Sequence[Note]) -> str:
    name = project.usage_name if role == "usage" else project.development_name
    description = (
        f"Use when invoking, configuring, integrating, validating, installing, or "
        f"troubleshooting {project.project_id} consumer interfaces."
        if role == "usage"
        else f"Use when changing, testing, reviewing, or releasing "
        f"{project.project_id} implementation or development infrastructure."
    )
    lines = [
        "---",
        "type: Agent Skill",
        f"title: {render_scalar(project.project_id + ' ' + role.title() + ' Skill')}",
        "status: stable",
        f"name: {name}",
        f"description: {render_scalar(description)}",
        f"audience: {role}",
        "---",
        "",
        f"# {project.project_id} {role.title()} Skill",
        "",
        f"<!-- {GENERATED_MARKER} -->",
        "",
        f"Working State: `{project.working_state}`",
        "",
    ]
    if role == "development":
        lines.extend(
            [
                "## Required companion",
                "",
                f"Load `{project.usage_name}` before contributor work that invokes, configures, integrates, or troubleshoots the Project.",
                "",
            ]
        )
    lines.extend(record_first_contract(project))
    lines.extend(["## Topics", ""])
    if notes:
        for note in notes:
            reference = safe_reference_path(note).as_posix()
            lines.append(f"- [{note.title}]({reference})")
    elif role == "development":
        lines.append(
            f"- No stable Contributor-only topics are available; use `{project.usage_name}` for current Project behavior."
        )
    lines.extend(
        [
            "",
            "Load only the topic references needed for the current task.",
            "",
        ]
    )
    return "\n".join(lines)


