def update_markdown_metadata(text: str, updates: dict[str, Any]) -> str:
    document = parse_markdown(text)
    lines = text.splitlines(keepends=True)
    if document.frontmatter_range is None:
        metadata_lines = ["---\n"]
        for key, value in updates.items():
            metadata_lines.extend(render_entry(key, value))
        metadata_lines.extend(["---\n", "\n"])
        return "".join(metadata_lines) + text.lstrip("\n")

    start, end = document.frontmatter_range
    existing = lines[start + 1 : end]
    spans: dict[str, tuple[int, int]] = {}
    current: str | None = None
    for index, line in enumerate(existing):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if not line[:1].isspace() and not stripped.startswith("-"):
            key = stripped.split(":", 1)[0].strip().strip("\"'")
            current = key
            if key not in spans:
                spans[key] = (index, index)
        elif current is not None:
            first, last = spans[current]
            spans[current] = (first, index)
    span_by_start = {span[0]: key for key, span in spans.items()}

    rebuilt: list[str] = []
    index = 0
    while index < len(existing):
        key = span_by_start.get(index)
        if key is not None and key in updates:
            rebuilt.extend(render_entry(key, updates[key]))
            index = spans[key][1] + 1
            continue
        rebuilt.append(existing[index])
        index += 1
    for key, value in updates.items():
        if key not in spans:
            rebuilt.extend(render_entry(key, value))

    frontmatter = "".join([lines[start], *rebuilt, lines[end]])
    body = "".join(lines[:start] + lines[end + 1 :]).lstrip("\n")
    return frontmatter.rstrip("\n") + "\n\n" + body


def require_frontmatter(text: str, relative_path: str) -> MarkdownDocument:
    document = parse_markdown(text, context=relative_path)
    if document.frontmatter_range is None or document.frontmatter_range[0] != 0:
        raise KosmicError(
            f"OKF concept requires YAML frontmatter on line 1: {relative_path}"
        )
    return document


def validate_index_document(path: Path, bundle_root: Path) -> None:
    relative = path.relative_to(bundle_root).as_posix()
    text = path.read_text(encoding="utf-8")
    document = parse_markdown(text)
    is_root = path.parent == bundle_root
    if is_root:
        if document.frontmatter_range is None or document.frontmatter_range[0] != 0:
            raise KosmicError(f"bundle-root index.md must declare okf_version: {OKF_VERSION}")
        keys = set(document.metadata)
        if keys != {"okf_version"}:
            raise KosmicError(
                "bundle-root index.md frontmatter may contain only okf_version"
            )
        if str(document.metadata["okf_version"]) != OKF_VERSION:
            raise KosmicError(
                f"bundle-root index.md must declare okf_version: {OKF_VERSION}"
            )
    elif document.frontmatter_range is not None:
        raise KosmicError(f"nested index.md must not contain frontmatter: {relative}")

    if not re.search(r"^#\s+\S", document.body, flags=re.MULTILINE):
        raise KosmicError(f"index.md must contain at least one section heading: {relative}")
    if has_nonportable_wikilink(document.body):
        raise KosmicError(f"index.md contains non-portable Wikilink: {relative}")


def validate_log_document(path: Path, bundle_root: Path) -> None:
    relative = path.relative_to(bundle_root).as_posix()
    text = path.read_text(encoding="utf-8")
    document = parse_markdown(text)
    if document.frontmatter_range is not None:
        raise KosmicError(f"OKF log.md must not contain frontmatter: {relative}")
    headings = re.findall(r"^##\s+(.+?)\s*$", document.body, flags=re.MULTILINE)
    if not headings or any(not ISO_DATE_RE.fullmatch(heading) for heading in headings):
        raise KosmicError(
            f"OKF log.md requires ISO date-grouped entries: {relative}"
        )


def validate_okf_bundle(
    bundle_root: Path,
    *,
    require_index: bool,
    forbid_log: bool,
) -> None:
    if not bundle_root.is_dir():
        raise KosmicError(f"missing OKF bundle: {bundle_root}")
    root_index = bundle_root / "index.md"
    if require_index and not root_index.is_file():
        raise KosmicError(f"missing bundle-root index.md: {root_index}")

    for path in sorted(bundle_root.rglob("*.md")):
        relative = path.relative_to(bundle_root).as_posix()
        if path.name == "index.md":
            validate_index_document(path, bundle_root)
            continue
        if path.name == "log.md":
            if forbid_log:
                raise KosmicError(
                    f"Project workflow logs must remain outside the notes bundle: {relative}"
                )
            validate_log_document(path, bundle_root)
            continue
        document = require_frontmatter(path.read_text(encoding="utf-8"), relative)
        concept_type = str(document.metadata.get("type") or "").strip()
        if not concept_type:
            raise KosmicError(f"OKF concept requires a non-empty type: {relative}")


def validated_stale_after(value: Any, relative_path: str) -> date | None:
    if value in (None, ""):
        return None
    raw = str(value).strip()
    if not ISO_DATE_RE.fullmatch(raw):
        raise KosmicError(
            f"invalid stale_after in {relative_path}; expected YYYY-MM-DD"
        )
    try:
        return date.fromisoformat(raw)
    except ValueError as error:
        raise KosmicError(
            f"invalid stale_after date in {relative_path}: {raw}"
        ) from error


def as_path_list(value: Any) -> list[str]:
    if value is None or value == "":
        return []
    if isinstance(value, list):
        return [str(item) for item in value]
    return [str(value)]


def note_skill_candidate(metadata: dict[str, Any], relative_path: str) -> bool:
    """ADR-F reader: skill-material candidacy; only an absent key reads false."""
    if "skill_candidate" not in metadata:
        return False
    value = metadata.get("skill_candidate")
    if not isinstance(value, bool):
        raise KosmicError(
            f"invalid skill_candidate in {relative_path}; "
            f"expected true or false, got {value!r}"
        )
    return value


def note_skill_resources(metadata: dict[str, Any], relative_path: str) -> list[str]:
    """ADR-F reader: stable ids of skill topics actually using this note; only an absent key reads empty."""
    if "skill_resources" not in metadata:
        return []
    value = metadata.get("skill_resources")
    if not isinstance(value, list):
        raise KosmicError(
            f"invalid skill_resources in {relative_path}; expected a list of "
            f"stable skill-topic ids, got {value!r}"
        )
    resources: list[str] = []
    for item in value:
        if not isinstance(item, str) or not item or re.search(r"\s", item):
            raise KosmicError(
                f"invalid skill_resources entry {item!r} in {relative_path}; "
                "expected a non-empty stable skill-topic id without whitespace"
            )
        resources.append(item)
    return resources


def validated_note_updated(value: Any, relative_path: str) -> str:
    """Note ``updated`` reader: legacy YYYY-MM-DD or an aware UTC instant; never invented."""
    updated = str(value or "").strip()
    if not updated:
        return ""
    if ISO_DATE_RE.fullmatch(updated):
        return updated
    if UTC_TIMESTAMP_RE.fullmatch(updated):
        try:
            datetime.fromisoformat(updated.replace("Z", "+00:00"))
        except ValueError as error:
            raise KosmicError(
                f"invalid updated in {relative_path}; expected a real UTC "
                f"instant: {updated!r}"
            ) from error
        return updated
    raise KosmicError(
        f"invalid updated in {relative_path}; expected YYYY-MM-DD or an "
        "ISO-8601 UTC instant (YYYY-MM-DDTHH:MM:SS[.ffffff]Z): "
        f"{updated!r}"
    )


def validate_artifact_role(document: MarkdownDocument, relative: str, *, required: bool) -> str:
    role = str(document.metadata.get("artifact_role") or "").strip()
    if not role:
        if required:
            raise KosmicError(f"artifact_role is required in {relative}")
        return ""
    if role not in ARTIFACT_ROLES:
        raise KosmicError(f"invalid artifact_role '{role}' in {relative}")
    if role == "procedure":
        if not str(document.metadata.get("outcome") or "").strip():
            raise KosmicError(f"procedure requires a bounded outcome in {relative}")
        sections: dict[str, list[str]] = {}
        current: str | None = None
        for line in document.body.splitlines():
            if line.startswith("## "):
                current = line[3:].strip().casefold()
                sections.setdefault(current, [])
            elif current is not None:
                sections[current].append(line)
        missing = sorted(
            heading
            for heading in PROCEDURE_SECTIONS
            if heading not in sections
            or not any(line.strip() for line in sections[heading])
        )
        if missing:
            raise KosmicError(
                f"procedure {relative} missing non-empty behavioral sections: "
                + ", ".join(missing)
            )
    return role


def _note_derivation_slugs(document: MarkdownDocument, relative: str) -> set[str]:
    declared: set[str] = set()
    for path in as_path_list(document.metadata.get("derivations")):
        match = re.fullmatch(r"mathdocs/([a-z0-9]+(?:-[a-z0-9]+)*)\.py", path)
        if match is None:
            raise KosmicError(
                f"{relative} derivations entry must be mathdocs/<slug>.py: {path}"
            )
        declared.add(match.group(1))
    return declared


def validate_note_math_markers(
    document: MarkdownDocument,
    relative: str,
    registry: MathRegistry,
) -> None:
    declared = _note_derivation_slugs(document, relative)
    for slug in sorted(declared):
        entry = registry.entries.get(slug)
        if entry is None or entry.status == "deprecated":
            raise KosmicError(
                f"{relative} derivations references unknown active MathDoc: mathdocs/{slug}.py"
            )

    outside_lines: list[str] = []

    def collect(line: str) -> str:
        outside_lines.append(line)
        return line

    rewrite_outside_fences(document.body, collect)
    outside = "".join(outside_lines)
    result_matches = list(NOTE_MATH_RESULT_RE.finditer(outside))
    exposition_matches = list(NOTE_MATH_EXPOSITION_RE.finditer(outside))
    display_delimiters = len(re.findall(r"(?m)^\s*\$\$\s*$", outside))
    if display_delimiters % 2:
        raise KosmicError(f"{relative} contains an unmatched display-math delimiter")
    if display_delimiters // 2 != len(result_matches) + len(exposition_matches):
        raise KosmicError(
            f"{relative} display math requires one MathDoc marker per equation"
        )
    if outside.count("<!-- MathDoc:") != len(result_matches):
        raise KosmicError(f"{relative} contains a malformed MathDoc result marker")
    if outside.count("<!-- MathDoc-Exposition:") != len(exposition_matches):
        raise KosmicError(f"{relative} contains a malformed MathDoc exposition marker")

    for match in result_matches:
        project_id, slug, name, latex = match.groups()
        if project_id != registry.project_id:
            raise KosmicError(
                f"{relative} MathDoc project id must be {registry.project_id}"
            )
        if slug not in declared:
            raise KosmicError(
                f"{relative} MathDoc {slug} requires derivations: [mathdocs/{slug}.py]"
            )
        entry = registry.entries[slug]
        result = next((item for item in entry.results if item.name == name), None)
        if result is None:
            raise KosmicError(f"{relative} references unknown MathDoc {slug}#{name}")
        if latex.replace("\r\n", "\n") != result.latex:
            raise KosmicError(
                f"{relative} MathDoc {slug}#{name} LaTeX differs from verified result"
            )

    for match in exposition_matches:
        project_id, slug, _ = match.groups()
        if project_id != registry.project_id:
            raise KosmicError(
                f"{relative} MathDoc exposition project id must be {registry.project_id}"
            )
        if slug not in declared:
            raise KosmicError(
                f"{relative} MathDoc exposition {slug} requires "
                f"derivations: [mathdocs/{slug}.py]"
            )


def _validate_note_document(
    document: MarkdownDocument,
    relative: str,
    project_root: Path,
    math_registry: MathRegistry | None = None,
) -> None:
    if not str(document.metadata.get("type") or "").strip():
        raise KosmicError(f"OKF concept requires a non-empty type: {relative}")
    status = str(document.metadata.get("status") or "").strip().lower()
    if status not in NOTE_STATUSES:
        raise KosmicError(
            f"invalid Project Knowledge status '{status}' in {relative}; "
            "expected draft, stable, or deprecated"
        )
    updated = validated_note_updated(document.metadata.get("updated"), relative)
    validate_artifact_role(
        document, relative,
        required=bool(updated[:10] >= "2026-09-07"),
    )
    note_skill_candidate(document.metadata, relative)
    note_skill_resources(document.metadata, relative)
    validated_stale_after(document.metadata.get("stale_after"), relative)
    if status == "stable":
        if math_registry is not None:
            validate_note_math_markers(document, relative, math_registry)
    if has_nonportable_wikilink(document.body):
        raise KosmicError(f"non-portable Wikilink in Project Knowledge: {relative}")


def validate_notes_bundle(
    notes_dir: Path, math_registry: MathRegistry | None = None
) -> None:
    validate_okf_bundle(notes_dir, require_index=True, forbid_log=True)
    for path in sorted(notes_dir.rglob("*.md")):
        if path.name in {"index.md", "log.md"}:
            continue
        relative = path.relative_to(notes_dir).as_posix()
        document = require_frontmatter(path.read_text(encoding="utf-8"), relative)
        _validate_note_document(document, relative, notes_dir.parent, math_registry)


def validate_math_metadata(
    slug: str,
    script_path: Path,
    status: str,
    metadata: dict[str, Any],
    require_current_source: bool,
) -> dict[str, str | None]:
    fields = (
        "source_sha256",
        "python_version",
        "sympy_version",
        "verified_at",
        "verified_host",
        "verified_directory",
    )
    values = {
        field: str(metadata.get(field) or "").strip() or None for field in fields
    }
    if status == "stable":
        missing = [field for field in fields if values[field] is None]
        if missing:
            raise KosmicError(
                f"stable Math Derivation {slug} requires metadata: "
                + ", ".join(missing)
            )
    source_sha256 = values["source_sha256"]
    if source_sha256 is not None:
        if not SHA256_RE.fullmatch(source_sha256):
            raise KosmicError(
                f"Math Derivation {slug} source_sha256 must be lowercase SHA-256"
            )
        if (
            require_current_source
            and source_sha256 != sha256_bytes(script_path.read_bytes())
        ):
            raise KosmicError(
                f"Math Derivation {slug} source_sha256 does not match {slug}.py"
            )
    for field in ("python_version", "sympy_version"):
        value = values[field]
        if value is not None and not VERSION_RE.fullmatch(value):
            raise KosmicError(
                f"Math Derivation {slug} {field} is not a valid version"
            )
    verified_at = values["verified_at"]
    if verified_at is not None and not UTC_TIMESTAMP_RE.fullmatch(verified_at):
        raise KosmicError(
            f"Math Derivation {slug} verified_at must be an ISO-8601 UTC timestamp"
        )
    verified_directory = values["verified_directory"]
    if verified_directory is not None and not Path(verified_directory).is_absolute():
        raise KosmicError(
            f"Math Derivation {slug} verified_directory must be absolute"
        )
    return values




def render_math_results(
    project_id: str, slug: str, results: Sequence[MathResult]
) -> str:
    blocks = "".join(
        f"<!-- MathDoc: {project_id}/{slug}#{result.name} -->\n"
        f"$$\n{result.latex}\n$$\n"
        f"<!-- KOSMIC-SREPR: {result.srepr} -->\n"
        for result in results
    )
    return (
        f"{MATH_RESULTS_START}\n"
        "## Verified Results\n\n"
        f"{blocks}"
        f"{MATH_RESULTS_END}"
    )


def parse_math_results(
    body: str, project_id: str, slug: str, status: str
) -> tuple[MathResult, ...]:
    starts = body.count(MATH_RESULTS_START)
    ends = body.count(MATH_RESULTS_END)
    if starts == 0 and ends == 0 and status != "stable":
        return ()
    if starts != 1 or ends != 1:
        raise KosmicError(
            f"Math Derivation {slug} must contain exactly one generated result region"
        )
    start = body.index(MATH_RESULTS_START)
    end = body.index(MATH_RESULTS_END, start) + len(MATH_RESULTS_END)
    region = body[start:end]
    matches = list(MATH_RESULT_RE.finditer(region))
    results = tuple(
        MathResult(
            name=match.group(3),
            latex=match.group(4).replace("\r\n", "\n"),
            srepr=match.group(5).replace("\r\n", "\n"),
        )
        for match in matches
        if match.group(1) == project_id and match.group(2) == slug
    )
    if not results:
        raise KosmicError(f"Math Derivation {slug} has no verified results")
    names = [result.name for result in results]
    if names != sorted(names) or len(names) != len(set(names)):
        raise KosmicError(
            f"Math Derivation {slug} result names must be sorted and unique"
        )
    if region != render_math_results(project_id, slug, results):
        raise KosmicError(
            f"Math Derivation {slug} generated result region is malformed"
        )
    return results


def load_math_registry(
    project: Project,
    mathdocs_dir: Path | None = None,
    *,
    require_current_source: bool = True,
    only_slugs: Sequence[str] | None = None,
) -> MathRegistry:
    selected = None if only_slugs is None else set(only_slugs)
    if selected is not None:
        for slug in selected:
            if not MATH_SLUG_RE.fullmatch(slug):
                raise KosmicError(f"invalid selected derivation slug: {slug}")
        if not selected:
            return MathRegistry(project_id=project.project_id, entries={})
    root = mathdocs_dir or project.mathdocs_dir
    index_path = root / "index.md"
    if not root.is_dir() or not index_path.is_file():
        raise KosmicError(
            f"missing Project mathdocs index: {index_path}; run init or migrate"
        )

    scripts: dict[str, Path] = {}
    notes: dict[str, Path] = {}
    for path in sorted(root.iterdir()):
        if not path.is_file() or path.name == "index.md":
            continue
        if path.suffix not in {".py", ".md"}:
            continue
        slug = path.stem
        if selected is not None and slug not in selected:
            continue
        if not MATH_SLUG_RE.fullmatch(slug):
            raise KosmicError(f"invalid mathdocs slug in {path.name}")
        target = scripts if path.suffix == ".py" else notes
        target[slug] = path

    missing_notes = sorted(set(scripts) - set(notes))
    missing_scripts = sorted(set(notes) - set(scripts))
    if missing_notes or missing_scripts:
        details = [f"{slug}.py" for slug in missing_notes]
        details.extend(f"{slug}.md" for slug in missing_scripts)
        raise KosmicError(
            "unpaired mathdocs files: " + ", ".join(details)
        )

    if selected is not None:
        missing_selected = sorted(selected - set(scripts))
        if missing_selected:
            raise KosmicError("selected MathDoc is missing: " + ", ".join(missing_selected))
    entries: dict[str, MathEntry] = {}
    for slug in sorted(scripts):
        note_path = notes[slug]
        document = require_frontmatter(
            note_path.read_text(encoding="utf-8"), f"mathdocs/{note_path.name}"
        )
        if str(document.metadata.get("type") or "").strip() != "Math Derivation":
            raise KosmicError(
                f"mathdocs/{note_path.name} type must be Math Derivation"
            )
        status = str(document.metadata.get("status") or "").strip().lower()
        if status not in NOTE_STATUSES:
            raise KosmicError(
                f"invalid Math Derivation status '{status}' in {note_path.name}"
            )
        if str(document.metadata.get("derivation") or "").strip() != f"{slug}.py":
            raise KosmicError(
                f"mathdocs/{note_path.name} derivation must be {slug}.py"
            )
        metadata = validate_math_metadata(
            slug,
            scripts[slug],
            status,
            document.metadata,
            require_current_source,
        )
        results = parse_math_results(
            document.body, project.project_id, slug, status
        )
        entries[slug] = MathEntry(
            slug=slug,
            script_path=scripts[slug],
            note_path=note_path,
            status=status,
            document=document,
            source_sha256=metadata["source_sha256"],
            python_version=metadata["python_version"],
            sympy_version=metadata["sympy_version"],
            verified_at=metadata["verified_at"],
            verified_host=metadata["verified_host"],
            verified_directory=metadata["verified_directory"],
            results=results,
        )

    index_text = index_path.read_text(encoding="utf-8")
    if not index_text.startswith(MATH_INDEX_HEADER):
        raise KosmicError(
            "mathdocs/index.md must start with the reserved Math Derivations table"
        )
    rows: dict[str, tuple[str, str]] = {}
    for line in index_text.splitlines()[4:]:
        if not line.strip() or line.lstrip().startswith("<!--"):
            continue
        match = MATH_INDEX_ROW_RE.fullmatch(line.strip())
        if selected is not None and (match is None or match.group(1) not in selected):
            if match is None:
                columns = line.strip().strip("|").split("|")
                slug_column = columns[0].strip() if columns else ""
                link = re.fullmatch(r"\[([^\]]+)\]\([^)]*\)", slug_column)
                if link:
                    row_slug = link.group(1)
                elif slug_column.startswith("["):
                    # Broken link syntax still names its slug before "]".
                    row_slug = slug_column[1:].split("]", 1)[0].strip()
                else:
                    row_slug = slug_column.removesuffix(".md").strip()
                if row_slug in selected:
                    raise KosmicError(
                        f"invalid mathdocs index row for selected derivation: {line}"
                    )
            continue
        if not line.lstrip().startswith("|"):
            raise KosmicError(f"invalid mathdocs index line: {line}")
        if match is None:
            raise KosmicError(f"invalid mathdocs index row: {line}")
        slug, href, status, summary = match.groups()
        if slug in rows:
            raise KosmicError(f"duplicate mathdocs index row: {slug}")
        if href != f"{slug}.md":
            raise KosmicError(
                f"mathdocs index link for {slug} must be {slug}.md"
            )
        rows[slug] = (status, summary.strip())

    active = {slug for slug, entry in entries.items() if entry.status != "deprecated"}
    unknown = sorted(set(rows) - active)
    missing = sorted(active - set(rows))
    if unknown:
        raise KosmicError(
            "mathdocs index references unknown or deprecated derivations: "
            + ", ".join(unknown)
        )
    if missing:
        raise KosmicError(
            "mathdocs index is missing derivations: " + ", ".join(missing)
        )
    for slug in sorted(active):
        row_status, _ = rows[slug]
        if row_status != entries[slug].status:
            raise KosmicError(
                f"mathdocs index status for {slug} is {row_status}; "
                f"note status is {entries[slug].status}"
            )
    return MathRegistry(project_id=project.project_id, entries=entries)


def validate_project_content(project: Project) -> MathRegistry:
    registry = load_math_registry(project)
    validate_notes_bundle(project.notes_dir, registry)
    return registry


def _validate_record_content(
    project: Project, document: MarkdownDocument
) -> MathRegistry:
    """Validate the record's explicitly declared knowledge and math closure."""
    slugs = set(as_string_list(document.metadata.get("derivations")))
    notes: list[tuple[MarkdownDocument, str]] = []
    for reference in as_string_list(document.metadata.get("related_notes")):
        path = resolve_related_note(project, reference)
        if not path.is_file():
            raise KosmicError(f"declared Project knowledge is missing: {reference}")
        relative = path.relative_to(project.notes_dir).as_posix()
        note = require_frontmatter(path.read_text(encoding="utf-8"), relative)
        if str(note.metadata.get("status") or "").strip().lower() == "deprecated":
            raise KosmicError(f"declared Project knowledge is deprecated: {reference}")
        stale_after = validated_stale_after(note.metadata.get("stale_after"), relative)
        if stale_after is not None and date.today() >= stale_after:
            raise KosmicError(f"declared Project knowledge is stale: {reference}")
        if note.metadata.get("usage_stale") is True:
            raise KosmicError(f"declared Project knowledge is Usage-stale: {reference}")
        slugs.update(_note_derivation_slugs(note, relative))
        notes.append((note, relative))
    registry = load_math_registry(project, only_slugs=sorted(slugs))
    for note, relative in notes:
        _validate_note_document(note, relative, project.root, registry)
    return registry


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def json_text(value: Any) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def validate_project_id(project_id: str) -> None:
    if not PROJECT_ID_RE.fullmatch(project_id):
        raise KosmicError(
            "invalid Project Identifier; use a lowercase, hyphen-separated slug "
            "such as 'acme-billing-api'"
        )


def project_entry_path(root: Path) -> Path:
    return root / "ProjectEntry.md"


def read_project_id(root: Path) -> str | None:
    entry = project_entry_path(root)
    if not entry.is_file():
        return None
    document = parse_markdown(entry.read_text(encoding="utf-8"))
    value = document.metadata.get("project_id")
    return str(value) if value else None


def check_project_id_collision(root: Path, project_id: str) -> None:
    projects_dir = root.parent
    if projects_dir.name != "Projects" or not projects_dir.is_dir():
        return
    for sibling in sorted(projects_dir.iterdir()):
        if not sibling.is_dir() or sibling.resolve() == root.resolve():
            continue
        if read_project_id(sibling) == project_id:
            raise KosmicError(
                f"Project Identifier collision: '{project_id}' is already assigned to {sibling}",
                exit_code=4,
            )


def load_project(root: Path, require_id: bool = True) -> Project:
    root = root.expanduser().resolve()
    entry = project_entry_path(root)
    if not entry.is_file():
        raise KosmicError(f"missing Project entry: {entry}")
    document = parse_markdown(entry.read_text(encoding="utf-8"))
    project_id_value = document.metadata.get("project_id")
    if not project_id_value:
        if require_id:
            raise KosmicError(
                "ProjectEntry.md has no project_id; initialize or migrate the Project first"
            )
        project_id_value = ""
    project_id = str(project_id_value)
    if project_id:
        validate_project_id(project_id)
        check_project_id_collision(root, project_id)
    working_state = str(document.metadata.get("working_state") or "working-tree")
    status_root_text = str(document.metadata.get("status_root") or "").strip()
    return Project(
        root=root,
        entry=entry,
        project_id=project_id,
        working_state=working_state,
        status_root=Path(status_root_text) if status_root_text else None,
    )


def note_title(body: str, path: Path) -> str:
    for line in body.splitlines():
        match = re.match(r"^#\s+(.+?)\s*$", line)
        if match:
            return match.group(1)
    return path.stem.replace("_", " ").replace("-", " ").title()


def normalize_audience(value: Any, relative_path: str) -> tuple[str, bool]:
    if value is None or value == "":
        return "development", True
    audience = str(value).strip().lower()
    if audience not in AUDIENCES:
        raise KosmicError(
            f"invalid Audience Scope '{value}' in {relative_path}; expected development, usage, or both"
        )
    return audience, False


def collect_projection_plan(project: Project) -> ProjectionPlan:
    if not project.notes_dir.is_dir():
        raise KosmicError(f"missing Project notes directory: {project.notes_dir}")
    validate_project_content(project)

    usage: list[Note] = []
    development: list[Note] = []
    unscoped: list[str] = []
    today = date.today()
    for path in sorted(project.notes_dir.rglob("*.md")):
        if path.name in {"index.md", "log.md"}:
            continue
        relative = path.relative_to(project.root).as_posix()
        source = path.read_bytes()
        document = parse_markdown(source.decode("utf-8"))
        status = str(document.metadata.get("status") or "").strip().lower()
        if status != "stable":
            continue
        stale_after = validated_stale_after(
            document.metadata.get("stale_after"), relative
        )
        if stale_after is not None and today >= stale_after:
            continue
        if document.metadata.get("usage_stale") is True:
            continue
        audience, is_unscoped = normalize_audience(document.metadata.get("audience"), relative)
        body = document.body.strip()
        if not body:
            raise KosmicError(f"stable note has no projectable content: {relative}")
        note = Note(
            path=path,
            relative_path=relative,
            title=note_title(body, path),
            body=body + "\n",
            source_hash=sha256_bytes(source),
            audience=audience,
            artifact_role=str(document.metadata.get("artifact_role") or ""),
            unscoped=is_unscoped,
        )
        if is_unscoped:
            unscoped.append(relative)
        if audience in {"usage", "both"}:
            usage.append(note)
        if audience == "development":
            development.append(note)

    return ProjectionPlan(
        project=project,
        usage_notes=tuple(usage),
        development_notes=tuple(development),
        unscoped_notes=tuple(unscoped),
    )


def safe_reference_path(note: Note) -> Path:
    relative = Path(note.relative_path)
    if relative.parts[0] == "notes":
        relative = Path(*relative.parts[1:])
    if any(part in {"", ".", ".."} for part in relative.parts):
        raise KosmicError(f"unsafe note path: {note.relative_path}")
    return Path("references") / relative


def projected_reference(project: Project, note: Note, body: str) -> str:
    metadata = {
        "type": "Project Knowledge",
        "title": note.title,
        "status": "stable",
        "kosmic_generated": True,
        "project_id": project.project_id,
        "working_state": project.working_state,
        "audience": note.audience,
        "artifact_role": note.artifact_role,
        "source": note.relative_path,
        "source_sha256": note.source_hash,
    }
    header = ["---\n"]
    header.extend(f"{key}: {render_scalar(value)}\n" for key, value in metadata.items())
    header.extend(["---\n", f"\n<!-- {GENERATED_MARKER} -->\n\n"])
    return "".join(header) + body

MARKDOWN_LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")


def demote_unshipped_links(
    body: str, note: Note, package_paths: set[str]
) -> tuple[str, list[str]]:
    """Demote body links whose targets are not projected into this package."""
    demoted: list[str] = []
    note_dir = Path(note.relative_path).parent

    def rewrite(line: str) -> str:
        def replace(match: re.Match[str]) -> str:
            text, target = match.group(1), match.group(2)
            if "://" in target or target.startswith(("#", "mailto:")):
                return match.group(0)
            path_text = target.split("#", 1)[0]
            if not path_text:
                return match.group(0)
            candidate = Path(path_text)
            if candidate.suffix != ".md":
                return match.group(0)
            resolved = Path(
                os.path.normpath((note_dir / candidate).as_posix())
            ).as_posix()
            if resolved in package_paths:
                return match.group(0)
            demoted.append(f"{note.relative_path} -> {target}")
            return f"**{text}**"

        return MARKDOWN_LINK_RE.sub(replace, line)

    return rewrite_outside_fences(body, rewrite), demoted




