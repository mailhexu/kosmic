        f"okf_version: {render_scalar(OKF_VERSION)}\n"
        "---\n\n"
        "# Agent Skills\n\n"
        f"* [Usage Skill]({project.usage_name}/SKILL.md) - "
        "Consumer guidance for supported Project interfaces.\n"
