def install_named_adapter(project: Project, adapter: str, home: Path, *,
                          work_record: str | None = None) -> Path:
    # AD-SW8-R2: the canonical Skill Pair is the triggering source; the
    # adapter destination is a command-declared derived target authorized by
    # the same record's derived_outputs before any directory creation.
    destination_root = adapter_root(adapter, home.expanduser().resolve())
    record = require_work_record(project.root, [project.canonical_root],
                                 work_record=work_record, purpose="install")
    validate_current_projection(project, project.canonical_root)
    destination_root.mkdir(parents=True, exist_ok=True)
    names = (project.usage_name, project.development_name)
    for name in names:
        destination = destination_root / name
        if destination.exists() and installed_project_id(destination) != project.project_id:
            raise KosmicError(
                f"installation collision at {destination}; existing skill is not this Project",
                exit_code=4,
            )

    staging = Path(tempfile.mkdtemp(prefix=".kosmic-install-", dir=destination_root))
    backup = Path(tempfile.mkdtemp(prefix=".kosmic-backup-", dir=destination_root))
    moved_old: list[str] = []
    installed_new: list[str] = []
    try:
        for name in names:
            shutil.copytree(project.canonical_root / name, staging / name)
        for name in names:
            destination = destination_root / name
            if destination.exists():
                os.replace(destination, backup / name)
                moved_old.append(name)
        for index, name in enumerate(names):
            os.replace(staging / name, destination_root / name)
            installed_new.append(name)
            if index == 0 and os.environ.get("KOSMIC_FAIL_STAGE") == "install-after-first":
                raise OSError("injected adapter failure after first skill")
        for name in names:
            if directory_digest(destination_root / name) != directory_digest(
                project.canonical_root / name
            ):
                raise OSError(f"installed skill failed verification: {name}")
    except Exception:
        for name in installed_new:
            shutil.rmtree(destination_root / name, ignore_errors=True)
        for name in moved_old:
            if (backup / name).exists():
                os.replace(backup / name, destination_root / name)
        raise
    finally:
        shutil.rmtree(staging, ignore_errors=True)
        shutil.rmtree(backup, ignore_errors=True)
    return destination_root

def check_installation(project: Project, adapter: str, home: Path) -> Path:
    destination_root = adapter_root(adapter, home.expanduser().resolve())
    for name in (project.usage_name, project.development_name):
        canonical = project.canonical_root / name
        installed = destination_root / name
        if not installed.is_dir():
            raise KosmicError(f"installed Skill Pair is missing package: {installed}")
        if installed_project_id(installed) != project.project_id:
            raise KosmicError(f"installed Skill Pair identity mismatch: {installed}")
        if directory_digest(installed) != directory_digest(canonical):
            raise KosmicError(f"installed Skill Pair is stale or modified: {installed}")
    return destination_root


