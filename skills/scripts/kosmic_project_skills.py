def migrate_routines_report(
    project: Project,
    output: Path,
    legacy_candidates: Sequence[str] = (),
    unregistered_helpers: Sequence[str] = (),
) -> Path:
    """Write a deterministic, read-only report for explicitly supplied migration candidates."""
    library_root = project.root.parent.parent / "Skills"
    inventory_path = library_root / ".kosmic" / "routines.json"
    if not inventory_path.is_file():
        raise RoutineError("routine inventory is missing; run generate-library")
    inventory = read_json(inventory_path)
    rows = sorted(inventory.get("routines", []), key=lambda row: str(row["id"]))
    candidates = sorted(set(legacy_candidates))
    helpers = sorted(set(unregistered_helpers))
    lines = ["# Routine Migration Report", "", "## Canonical routines", ""]
    for row in rows:
        procedures = ", ".join(f"`{procedure}`" for procedure in row["procedures"]) or "none"
        lines.append(
            f"- `{row['id']}` — `{row['module']}::{row['symbol']}`; "
            f"hash `{row['routine_sha256']}`; callers: "
            + ", ".join(f"`{caller}`" for caller in row["callers"])
            + f"; procedures: {procedures}"
        )
    lines.extend(["", "## Explicitly supplied legacy candidates", ""])
    lines.extend(f"- `{candidate}`" for candidate in candidates)
    if not candidates:
        lines.append("- None supplied.")
    lines.extend(["", "## Explicit unregistered helpers", ""])
    lines.extend(f"- `{helper}`" for helper in helpers)
    if not helpers:
        lines.append("- None supplied.")
    lines.extend([
        "",
        "## Behavioral equivalence",
        "",
        "- Canonical publication behavior: whole-tree and managed-path success, "
        "failure before backup, failure after backup, restoration, and cleanup.",
        "- Evidence must compare baseline and candidate outcomes before another routine cutover.",
        "",
        "## Blockers",
        "",
        "- None." if rows else "- No canonical routines were discovered.",
        "",
    ])
    output = output.expanduser().resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    return output

def _check_math_proposal_routine_gates(
    project: Project, work_item: Path, document: MarkdownDocument, registry,
    source_root: Path,
) -> None:
    """Applicable math, Skill Proposal, and routine contract gates.

    Shared by the normal completion precheck and the plain ``--work-item``
    terminal entry: a historical receipt keeps its validation, and the
    record's current math/proposal/routine contracts must still hold. This
    group never reruns evolving knowledge, projection, or note-currentness
    checks, so later note or dataset evolution never revokes a receipt.
    """
    validate_math_implementation(project, registry, document, source_root)
    if "proposal_required" in document.metadata:
        proposal_required = document.metadata["proposal_required"]
        if not isinstance(proposal_required, bool):
            raise KosmicError("proposal_required must be true or false")
        proposal_value = document.metadata.get("skill_proposal")
        if not proposal_required:
            if proposal_value not in (None, "", []):
                raise KosmicError(
                    "proposal_required: false work item must not declare skill_proposal"
                )
        else:
            if not isinstance(proposal_value, str) or not proposal_value.strip():
                raise KosmicError(
                    "proposal_required: true requires exactly one skill_proposal path"
                )
            candidate = (work_item.parent / proposal_value).resolve()
            proposal = load_skill_proposal(project, candidate)
            if proposal.decision == "pending":
                raise KosmicError("Skill Proposal decision is still pending")
    if "routine_decision_required" in document.metadata and "routine_edge_change" not in document.metadata:
        raise KosmicError(
            "routine-aware work item must declare routine_edge_change: true or false"
        )
    if "routine_edge_change" in document.metadata:
        edge_change = document.metadata["routine_edge_change"]
        if not isinstance(edge_change, bool):
            raise KosmicError("routine_edge_change must be true or false")
        if edge_change and document.metadata.get("routine_decision_required") is not True:
            raise KosmicError(
                "routine_edge_change: true requires routine_decision_required: true"
            )
    if "routine_decision_required" in document.metadata:
        routine_required = document.metadata["routine_decision_required"]
        routine_paths = as_string_list(document.metadata.get("routine_proposals"))
        if not isinstance(routine_required, bool):
            raise KosmicError("routine_decision_required must be true or false")
        if not routine_required:
            if routine_paths:
                raise KosmicError("routine_decision_required: false requires empty routine_proposals")
            if not proposal_section(document.body, "Routine Decision"):
                raise KosmicError("routine_decision_required: false requires a Routine Decision reason")
        else:
            if not routine_paths:
                raise KosmicError("routine_decision_required: true requires routine_proposals")
            seen_targets: set[str] = set()
            for reference in routine_paths:
                proposal_path = (work_item.parent / reference).resolve()
                routine_proposal = load_skill_proposal(project, proposal_path)
                proposal_document = parse_markdown(proposal_path.read_text(encoding="utf-8"))
                if str(proposal_document.metadata.get("target_kind") or "") != "routine":
                    raise KosmicError("routine_proposals must reference routine target proposals")
                action = str(proposal_document.metadata.get("routine_action") or "")
                if action in {"create", "extend"} and routine_proposal.decision != "accepted":
                    raise KosmicError("create/extend routine proposal decision must be accepted")
                if action in {"create", "extend"} and not routine_proposal.behavioral_evidence:
                    raise KosmicError("create/extend routine proposal requires behavioral evidence")
                target_id = str(proposal_document.metadata.get("routine_id") or "")
                if target_id in seen_targets:
                    raise KosmicError(f"duplicate routine proposal target: {target_id}")
                seen_targets.add(target_id)


def _check_existing_completion(
    project: Project, work_item: Path, source_root: Path = Path.cwd(), *,
    check_status: bool = True, record_scoped: bool = False,
    record_owner: str | None = None,
) -> None:
    if not work_item.is_file():
        raise KosmicError(f"missing work item: {work_item}")
    dependencies = as_string_list(parse_markdown(work_item.read_text(encoding="utf-8")).metadata.get("depends_on"))
    for reference in dependencies:
        if reference.startswith(project.project_id + "/"):
            try:
                dependency = SpecCatalog(project.root).resolve(reference).path
            except SpecError:
                # Record-bound view keyed to the dependency's own owner.
                dependency = SpecCatalog.bounded_for_reference(
                    project.root, reference).resolve(reference).path
        else:
            dependency = (work_item.parent / reference.strip()).resolve()
        if not dependency.is_file():
            raise KosmicError(f"depends_on work item is missing: {reference}")
        status = str(parse_markdown(dependency.read_text(encoding="utf-8")).metadata.get("status") or "")
        if status != "done":
            raise KosmicError(f"depends_on work item is not done: {reference} ({status or 'unknown'})")
    if not work_item.is_file():
        raise KosmicError(f"missing work item: {work_item}")
    if (check_status and project.status_root is not None
            and status_drift(project, record_scoped=record_scoped,
                             record_owner=record_owner)):
        raise KosmicError(
            "STATUS_STALE: STATUS.md is missing or drifts from spec state; run "
            "generate-status --project <PROJECT>",
            exit_code=2,
        )
    document = parse_markdown(work_item.read_text(encoding="utf-8"))
    if __package__:
        from . import kosmic_completion
    else:
        import kosmic_completion
    kosmic_completion.reject_retired_completion_inputs(document.metadata, work_item.name)
    registry = _validate_record_content(project, document)
    if "consumer_interface_change" not in document.metadata:
        raise KosmicError(
            "work item must declare consumer_interface_change: true or false before completion"
        )
    affects_interface = document.metadata["consumer_interface_change"]
    if not isinstance(affects_interface, bool):
        raise KosmicError("consumer_interface_change must be true or false")
    _check_math_proposal_routine_gates(
        project, work_item, document, registry, source_root)
    if not affects_interface:
        return
    references = as_string_list(document.metadata.get("related_notes"))
    if not references:
        raise KosmicError(
            "Consumer Interface changes require at least one related stable usage or both note"
        )
    for reference in references:
        note_path = resolve_related_note(project, reference)
        if not note_path.is_file():
            raise KosmicError(f"related Consumer knowledge is missing: {reference}")
        note = parse_markdown(note_path.read_text(encoding="utf-8"))
        if str(note.metadata.get("status") or "").lower() != "stable":
            raise KosmicError(f"related Consumer knowledge is not stable: {reference}")
        stale_after = validated_stale_after(note.metadata.get("stale_after"), reference)
        if stale_after is not None and date.today() >= stale_after:
            raise KosmicError(f"related Consumer knowledge is stale: {reference}")
        if note.metadata.get("usage_stale") is True:
            raise KosmicError(f"related Consumer knowledge is Usage-stale: {reference}")
        audience, unscoped = normalize_audience(note.metadata.get("audience"), reference)
        if unscoped or audience not in {"usage", "both"}:
            raise KosmicError(
                f"related note is not Consumer-visible knowledge: {reference}"
            )
    _validate_record_projection(project, references)

def check_completion(
    project: Project, work_item: Path, source_root: Path = Path.cwd(), *,
    work_record: str | None = None,
) -> None:
    """Run record/receipt gates before all existing completion early returns.

    Canonical records resolve identically in both modes: a ``done``
    implementation record always requires approved ancestry and a valid
    receipt over its unchanged bytes, so a drifted, unreceipted, or
    hand-edited ``done`` never reports complete through the plain
    ``--work-item`` entry, while ``--work-record`` keeps the full gates.
    Genuinely non-canonical work-item files keep the read-only diagnostic
    path, but any scope or malformed-identity failure on the record's own
    path is re-raised by the record-bound view, which never enumerates
    unrelated subprojects.
    """
    record_scoped = False
    record_owner: str | None = None
    if __package__:
        from . import kosmic_completion
    else:
        import kosmic_completion
    record = None
    catalog = None
    try:
        catalog = SpecCatalog(project.root)
        record = catalog.resolve(work_item)
    except SpecError:
        try:
            # Record-bound view: an unrelated subproject's defect (including
            # its missing SubprojectEntry, which read_document reports as
            # SCOPE_DENIED during full-catalog enumeration) must not hide
            # this record's own authorization and completion gates. Genuine
            # scope violations on this record's own path are re-raised by
            # the bounded view below, which never enumerates unrelated
            # subprojects.
            catalog = SpecCatalog.bounded_for_reference(
                project.root, str(work_item))
            record = catalog.resolve(work_item)
        except SpecError as bounded_error:
            if work_record is not None or bounded_error.code == "SCOPE_DENIED":
                raise bounded_error
            record = None  # non-canonical file: diagnostic-only completion checks
            catalog = None
    if record is not None:
        if work_record is not None:
            # check-completion verifies, it never mutates: a done record must
            # reach the terminal gates instead of being denied as a phase
            # violation by implementation-only resolution.
            resolved = kosmic_work.resolve_work_record(
                project.root, work_record,
                allow_terminal=record.status == "done")
            if resolved.qualified_id != record.qualified_id:
                raise kosmic_work.WorkdirError(
                    "RECORD_NOT_AUTHORIZED",
                    f"{record.path}: --work-record names {resolved.qualified_id}")
            kosmic_completion.check_completion_gates(project.root, work_item, source_root)
            record_scoped = True
            record_owner = record.subproject_id
            if record.status == "done":
                return
        elif (record.status == "done"
              and record.kind in kosmic_work.IMPLEMENTATION_KINDS):
            # Terminal invariance: the plain --work-item entry must apply the
            # same done gates as --work-record, and the record's current
            # math/proposal/routine contracts must still hold — without
            # rerunning evolving knowledge, projection, or note-currentness
            # checks, so a valid receipt survives later note or dataset
            # evolution.
            kosmic_completion.check_done_record_gates(catalog, project.root, record)
            document = parse_markdown(work_item.read_text(encoding="utf-8"))
            registry = load_math_registry(
                project,
                only_slugs=as_string_list(document.metadata.get("derivations")))
            _check_math_proposal_routine_gates(
                project, work_item, document, registry, source_root)
            return
    # Diagnostic-only completion checks remain read-only and record-free.
    _check_existing_completion(project, work_item, source_root,
                               record_scoped=record_scoped,
                               record_owner=record_owner)


