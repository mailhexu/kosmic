def build_projection_root(plan: ProjectionPlan, destination: Path) -> list[str]:
    project = plan.project
    destination.mkdir(parents=True, exist_ok=False)
    (destination / "index.md").write_text(
        skill_bundle_index(project), encoding="utf-8", newline="\n"
    )
    demoted_links: list[str] = []
    roles = {
        "usage": (project.usage_name, plan.usage_notes),
        "development": (project.development_name, plan.development_notes),
    }
    for role, (name, notes) in roles.items():
        package = destination / name
        (package / "references").mkdir(parents=True)
        (package / "SKILL.md").write_text(
            router_text(project, role, notes), encoding="utf-8", newline="\n"
        )
        package_paths = {note.relative_path for note in notes}
        for note in notes:
            reference = package / safe_reference_path(note)
            reference.parent.mkdir(parents=True, exist_ok=True)
            body, demoted = demote_unshipped_links(note.body, note, package_paths)
            demoted_links.extend(demoted)
            reference.write_text(
                projected_reference(project, note, body), encoding="utf-8", newline="\n"
            )
        (package / PROJECTION_MANIFEST).write_text(
            json_text(projection_manifest(project, role, notes)),
            encoding="utf-8",
            newline="\n",
        )

    usage_package = destination / project.usage_name
    development_package = destination / project.development_name
    pair_manifest = {
        "generator_version": GENERATOR_VERSION,
        "project_id": project.project_id,
        "working_state": project.working_state,
        "usage": {
            "name": project.usage_name,
            "sha256": directory_digest(usage_package),
        },
        "development": {
            "name": project.development_name,
            "sha256": directory_digest(development_package),
            "requires": project.usage_name,
        },
    }
    (destination / PAIR_MANIFEST).write_text(
        json_text(pair_manifest), encoding="utf-8", newline="\n"
    )
    return demoted_links


def read_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise KosmicError(f"invalid projection manifest {path}: {error}") from error
    if not isinstance(value, dict):
        raise KosmicError(f"invalid projection manifest {path}: expected an object")
    return value


def validate_projection_root(project: Project, root: Path, check_sources: bool = True) -> None:
    if not root.is_dir():
        raise KosmicError(f"missing canonical Skill Pair: {root}")
    validate_okf_bundle(root, require_index=True, forbid_log=False)
    pair_path = root / PAIR_MANIFEST
    pair = read_json(pair_path)
    if pair.get("project_id") != project.project_id:
        raise KosmicError("canonical Skill Pair belongs to a different Project")
    if pair.get("working_state") != project.working_state:
        raise KosmicError("canonical Skill Pair describes a different Working State")

    expected_names = {project.usage_name, project.development_name}
    actual_skill_dirs = {path.name for path in root.iterdir() if path.is_dir()}
    if actual_skill_dirs != expected_names:
        raise KosmicError(
            f"canonical Skill Pair must contain exactly {sorted(expected_names)}; found {sorted(actual_skill_dirs)}"
        )

    for role, name in (("usage", project.usage_name), ("development", project.development_name)):
        package = root / name
        skill = package / "SKILL.md"
        manifest_path = package / PROJECTION_MANIFEST
        if not skill.is_file() or not manifest_path.is_file():
            raise KosmicError(f"incomplete {role} projection: {package}")
        manifest = read_json(manifest_path)
        if manifest.get("project_id") != project.project_id or manifest.get("role") != role:
            raise KosmicError(f"invalid {role} projection identity")
        if role == "development":
            requires = manifest.get("requires")
            if requires != [project.usage_name] or project.usage_name not in skill.read_text(
                encoding="utf-8"
            ):
                raise KosmicError("Development Skill does not resolve its paired Usage Skill")
        if check_sources:
            for source in manifest.get("sources", []):
                if not isinstance(source, dict):
                    raise KosmicError(f"invalid source provenance in {manifest_path}")
                relative = source.get("path")
                expected_hash = source.get("sha256")
                if not isinstance(relative, str) or not isinstance(expected_hash, str):
                    raise KosmicError(f"invalid source provenance in {manifest_path}")
                source_path = project.root / relative
                if not source_path.is_file():
                    raise KosmicError(f"projection source is missing: {relative}")
                actual_hash = sha256_bytes(source_path.read_bytes())
                if actual_hash != expected_hash:
                    raise KosmicError(f"projection drift detected for source: {relative}")
        expected_digest = pair.get(role, {}).get("sha256")
        actual_digest = directory_digest(package)
        if expected_digest != actual_digest:
            raise KosmicError(f"projection drift detected in generated {role} package")


def directory_snapshot(root: Path) -> dict[str, bytes]:
    return {
        path.relative_to(root).as_posix(): path.read_bytes()
        for path in sorted(item for item in root.rglob("*") if item.is_file())
    }


def validate_current_projection(project: Project, output: Path) -> None:
    validate_projection_root(project, output, check_sources=True)
    plan = collect_projection_plan(project)
    if not plan.usage_notes:
        raise KosmicError("Usage Skill requires at least one stable usage or both note")
    with tempfile.TemporaryDirectory(prefix="kosmic-validation-") as temporary:
        expected = Path(temporary) / "skills"
        build_projection_root(plan, expected)
        if directory_snapshot(expected) != directory_snapshot(output):
            raise KosmicError("canonical Skill Pair is stale; regenerate it from Project Knowledge")


def publish_directory(staged: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    backup = destination.parent / f".{destination.name}.backup"
    if backup.exists():
        shutil.rmtree(backup)
    moved_old = False
    try:
        if destination.exists():
            os.replace(destination, backup)
            moved_old = True
        if os.environ.get("KOSMIC_FAIL_STAGE") == "after-backup":
            raise OSError("injected publication failure after backup")
        os.replace(staged, destination)
        if moved_old:
            shutil.rmtree(backup)
    except Exception:
        if destination.exists():
            shutil.rmtree(destination)
        if moved_old and backup.exists():
            os.replace(backup, destination)
        raise


def prior_source_hashes(destination: Path, project: Project) -> dict[str, str]:
    hashes: dict[str, str] = {}
    for name in (project.usage_name, project.development_name):
        manifest_path = destination / name / PROJECTION_MANIFEST
        if not manifest_path.is_file():
            continue
        for source in read_json(manifest_path).get("sources", []):
            if isinstance(source, dict) and isinstance(source.get("path"), str):
                hashes[source["path"]] = str(source.get("sha256") or "")
    return hashes


def generate(project: Project, output: Path | None = None) -> Path:
    destination = (output or project.canonical_root).expanduser().resolve()
    destination.parent.mkdir(parents=True, exist_ok=True)
    prior = prior_source_hashes(destination, project) if destination.is_dir() else {}
    plan = collect_projection_plan(project)
    if not plan.usage_notes:
        raise KosmicError("Usage Skill requires at least one stable usage or both note")
    temporary = Path(
        tempfile.mkdtemp(prefix=f".{destination.name}.staging-", dir=destination.parent)
    )
    shutil.rmtree(temporary)
    try:
        demoted_links = build_projection_root(plan, temporary)
        validate_projection_root(project, temporary, check_sources=True)
        if os.environ.get("KOSMIC_FAIL_STAGE") == "before-publish":
            raise OSError("injected publication failure before publish")
        publish_directory(temporary, destination)
    except Exception:
        if temporary.exists():
            shutil.rmtree(temporary)
        raise
    if destination == project.canonical_root:
        current = {
            note.relative_path: note.source_hash
            for note in (*plan.usage_notes, *plan.development_notes)
        }
        entries = []
        for path in sorted(set(prior) | set(current)):
            old_hash = prior.get(path)
            new_hash = current.get(path)
            if old_hash == new_hash:
                continue
            entries.append(
                {
                    "date": date.today().isoformat(),
                    "kind": "publication",
                    "targets": [path],
                    "refs": f"{old_hash or 'null'}->{new_hash or 'null'}",
                    "outcome": "published",
                    "reason": "",
                }
            )
        append_ledger_entries(project, entries)
    if plan.unscoped_notes:
        print(
            "warning: Unscoped Knowledge projected to Development only: "
            + ", ".join(plan.unscoped_notes),
            file=sys.stderr,
        )
    if demoted_links:
        print(
            "warning: demoted links to targets not projected into the same package: "
            + ", ".join(demoted_links),
            file=sys.stderr,
        )
    return destination


def rewrite_outside_fences(text: str, rewrite: Any) -> str:
    output: list[str] = []
    fence: str | None = None
    for line in text.splitlines(keepends=True):
        stripped = line.lstrip()
        marker = stripped[:3]
        if marker in {"```", "~~~"}:
            fence = None if fence == marker else marker
            output.append(line)
        elif fence is None:
            output.append(rewrite(line))
        else:
            output.append(line)
    return "".join(output)


def has_nonportable_wikilink(text: str) -> bool:
    found = False

    def inspect(line: str) -> str:
        nonlocal found
        found = found or WIKILINK_RE.search(line) is not None
        return line

    rewrite_outside_fences(text, inspect)
    return found


def resolve_wikilink_target(
    current: Path,
    raw_target: str,
    candidates: Sequence[Path],
) -> tuple[str, str]:
    target, separator, display = raw_target.partition("|")
    target = target.strip()
    display = display.strip() if separator else ""
    path_text, heading_separator, fragment = target.partition("#")
    path_text = path_text.strip()
    fragment = fragment.strip() if heading_separator else ""
    if fragment.startswith("^"):
        raise MigrationIncomplete(
            f"non-portable Obsidian block reference in {current.as_posix()}: [[{raw_target}]]"
        )

    if not path_text:
        destination = current
    else:
        cleaned = path_text.replace("\\", "/").removeprefix("/")
        if cleaned.startswith("notes/"):
            cleaned = cleaned[len("notes/") :]
        if cleaned.casefold() == "toc":
            destination = Path("index.md")
        else:
            cleaned_path = Path(cleaned)
            cleaned_without_suffix = cleaned_path.with_suffix("").as_posix().casefold()
            if "/" in cleaned:
                relative_candidate = Path(
                    os.path.normpath((current.parent / cleaned_path).as_posix())
                )
                matches = [
                    candidate
                    for candidate in candidates
                    if candidate.with_suffix("").as_posix().casefold()
                    in {
                        cleaned_without_suffix,
                        relative_candidate.with_suffix("").as_posix().casefold(),
                    }
                ]
            else:
                matches = [
                    candidate
                    for candidate in candidates
                    if candidate.stem.casefold() == cleaned_path.stem.casefold()
                ]
            if len(matches) > 1:
                joined = ", ".join(match.as_posix() for match in matches)
                raise MigrationIncomplete(
                    f"ambiguous Wikilink in {current.as_posix()}: [[{raw_target}]] "
                    f"matches {joined}"
                )
            if matches:
                destination = matches[0]
            else:
                destination = Path(
                    os.path.normpath((current.parent / cleaned_path).as_posix())
                )
                if destination.suffix != ".md":
                    destination = destination.with_suffix(".md")

    if display:
        label = display
    elif path_text:
        label = Path(path_text).stem
    else:
        label = fragment

    if not path_text and fragment:
        href = "#" + quote(fragment, safe="-_~")
    else:
        href = os.path.relpath(destination, current.parent or Path(".")).replace(
            os.sep, "/"
        )
        href = quote(href, safe="/.-_~")
        if fragment:
            href += "#" + quote(fragment, safe="-_~")
    return label, href


def migrate_wikilinks(text: str, current: Path, candidates: Sequence[Path]) -> str:
    def rewrite(line: str) -> str:
        def replace(match: re.Match[str]) -> str:
            if match.group(1):
                raise MigrationIncomplete(
                    f"non-portable Obsidian embed in {current.as_posix()}: {match.group(0)}"
                )
            label, href = resolve_wikilink_target(current, match.group(2), candidates)
            return f"[{label}]({href})"

        return WIKILINK_RE.sub(replace, line)

    return rewrite_outside_fences(text, rewrite)


def migrated_note_text(path: Path, text: str, candidates: Sequence[Path]) -> str:
    document = parse_markdown(text)
    status = str(document.metadata.get("status") or "").strip().lower()
    updates: dict[str, Any] = {
        "type": (
            "Project Notation"
            if path.name == "notation.md"
            else str(document.metadata.get("type") or "Project Knowledge")
        )
    }
    if status == "validated":
        updates["status"] = "stable"
    elif status == "stale":
        updates["status"] = "draft"
        updates["kosmic_legacy_status"] = "stale"
    elif status in NOTE_STATUSES:
        updates["status"] = status
    elif not status:
        updates["status"] = "draft"
    else:
        raise MigrationIncomplete(
            f"cannot migrate unknown Project Knowledge status '{status}' in {path.as_posix()}"
        )
    normalized = update_markdown_metadata(text, updates)
    return migrate_wikilinks(normalized, path, candidates)


def generated_notes_index(notes_dir: Path, candidates: Sequence[Path]) -> str:
    entries: list[str] = []
    for relative in candidates:
        path = notes_dir / relative
        document = parse_markdown(path.read_text(encoding="utf-8"))
        title = str(document.metadata.get("title") or note_title(document.body, path))
        href = quote(relative.as_posix(), safe="/.-_~")
        entries.append(f"* [{title}]({href}) - Project Knowledge concept.")
    body = "# Project Knowledge\n\n" + "\n".join(entries) + "\n"
    return (
        "---\n"
        f"okf_version: {render_scalar(OKF_VERSION)}\n"
        "---\n\n"
        + body
    )


def migrate_notes_bundle(project: Project) -> None:
    notes_dir = project.notes_dir
    notes_dir.mkdir(parents=True, exist_ok=True)
    temporary = Path(
        tempfile.mkdtemp(prefix=".notes-migration-", dir=notes_dir.parent)
    )
    shutil.rmtree(temporary)
    try:
        shutil.copytree(notes_dir, temporary)
        toc = temporary / "TOC.md"
        index = temporary / "index.md"
        if toc.exists() and index.exists():
            raise MigrationIncomplete(
                "cannot migrate notes bundle while both TOC.md and index.md exist"
            )

        candidates = tuple(
            path.relative_to(temporary)
            for path in sorted(temporary.rglob("*.md"))
            if path.name not in {"TOC.md", "index.md", "log.md"}
        )
        for relative in candidates:
            path = temporary / relative
            migrated = migrated_note_text(
                relative, path.read_text(encoding="utf-8"), candidates
            )
            path.write_text(migrated, encoding="utf-8", newline="\n")

        if toc.exists():
            toc_body = parse_markdown(toc.read_text(encoding="utf-8")).body
            toc_body = migrate_wikilinks(toc_body, Path("index.md"), candidates)
            index.write_text(
                "---\n"
                f"okf_version: {render_scalar(OKF_VERSION)}\n"
                "---\n\n"
                + toc_body.lstrip("\n"),
                encoding="utf-8",
                newline="\n",
            )
            toc.unlink()
        elif index.exists():
            document = parse_markdown(index.read_text(encoding="utf-8"))
            body = migrate_wikilinks(document.body, Path("index.md"), candidates)
            index.write_text(
                "---\n"
                f"okf_version: {render_scalar(OKF_VERSION)}\n"
                "---\n\n"
                + body.lstrip("\n"),
                encoding="utf-8",
                newline="\n",
            )
        else:
            index.write_text(
                generated_notes_index(temporary, candidates),
                encoding="utf-8",
                newline="\n",
            )

        validate_notes_bundle(temporary)
        publish_directory(temporary, notes_dir)
    except Exception:
        if temporary.exists():
            shutil.rmtree(temporary)
        raise


def ensure_project_structure(root: Path) -> None:
    for path in (
        root / "notes",
        root / "log",
        root / "specs" / "research",
        root / "specs" / "quick-tasks",
        root / "specs" / "epics",
        root / "specs" / "stories",
    ):
        path.mkdir(parents=True, exist_ok=True)


def assign_project_id(root: Path, project_id: str) -> Project:
    root = root.expanduser().resolve()
    validate_project_id(project_id)
    root.mkdir(parents=True, exist_ok=True)
    ensure_project_structure(root)
    entry = project_entry_path(root)
    if entry.exists():
        text = entry.read_text(encoding="utf-8")
        existing = parse_markdown(text).metadata.get("project_id")
        if existing and str(existing) != project_id:
            raise KosmicError(
                f"Project Identifier is immutable: Project already uses '{existing}'",
                exit_code=4,
            )
    else:
        text = f"# {root.name}\n\n## Overview\n\nDescribe this Project.\n"
    check_project_id_collision(root, project_id)
    updated = update_markdown_metadata(
        text, {"project_id": project_id, "working_state": "working-tree"}
    )
    atomic_write(entry, updated)
    return load_project(root)


def migrate(root: Path, project_id: str) -> Path:
    project = assign_project_id(root, project_id)
    migrate_notes_bundle(project)
    project = load_project(root)
    plan = collect_projection_plan(project)
    if plan.unscoped_notes:
        print(
            "Unscoped Knowledge remains Development-only until reviewed: "
            + ", ".join(plan.unscoped_notes),
            file=sys.stderr,
        )
    if not plan.usage_notes:
        raise MigrationIncomplete(
            "migration recorded Project identity and an OKF notes bundle, but pair "
            "publication is blocked until at least one stable note has audience: "
            "usage or audience: both"
        )
    return generate(project)


